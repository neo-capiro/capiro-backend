-- Encrypted text columns for the three derived-intelligence tables.
--
-- WHY
-- SegmentCommitService enforces the session's recording policy at the storage
-- layer. KeyQuote already had encrypted columns, so a sensitive session's quotes
-- persist. EntityMention, LiveActionItem and LiveSummaryCard did NOT, so for a
-- sensitive session their prose was computed and then DISCARDED — fail-closed and
-- deliberate, with a comment in that file promising "a future additive migration".
-- This is that migration.
--
-- The cost of not having it was measured on 2026-07-29: a 62-minute Senate hearing
-- (session cms64c5ne0088kouo5vdxrms0) logged `mentions=1..3 card=true` across ~111
-- segments — every one generated by the model and then thrown away — so its recap
-- fell back to raw transcript fragments with no entities, no action items and no
-- stance cards. `isSensitiveSession()` returns true for ANY client-linked session,
-- so this affected essentially every hearing worth recapping.
--
-- Scheme is VERBATIM KeyQuote's (AES-256-GCM, base64 payloads, nullable pair of
-- plaintext-or-ciphertext). No new crypto, no new conventions.
--
-- Naming: the two single-prose tables reuse KeyQuote's exact column names so the
-- existing `reveal()` helper works unmodified. LiveSummaryCard carries TWO prose
-- fields (title, body) and therefore needs two independent payloads, so its columns
-- are prefixed. That asymmetry is deliberate — one shared name set cannot hold two
-- independently-encrypted values, and folding them into a single JSON payload would
-- invent an encoding the rest of this domain does not use.

-- ── intel_entity_mention: entity_label is the prose ─────────────────────────────
-- entity_type is a category and entity_ref is a canonical id; neither is free text,
-- so both stay plaintext and remain queryable/indexable.
ALTER TABLE "intel_entity_mention"
  ADD COLUMN IF NOT EXISTS "text_ciphertext" TEXT,
  ADD COLUMN IF NOT EXISTS "iv" TEXT,
  ADD COLUMN IF NOT EXISTS "auth_tag" TEXT,
  ADD COLUMN IF NOT EXISTS "key_version" TEXT;

-- Required so an encrypted row can omit plaintext entirely. Dropping NOT NULL is
-- metadata-only in Postgres: no table rewrite, no lock beyond a brief ACCESS
-- EXCLUSIVE, and every existing row keeps its value.
ALTER TABLE "intel_entity_mention" ALTER COLUMN "entity_label" DROP NOT NULL;

-- ── intel_live_action_item: description is the prose ────────────────────────────
ALTER TABLE "intel_live_action_item"
  ADD COLUMN IF NOT EXISTS "text_ciphertext" TEXT,
  ADD COLUMN IF NOT EXISTS "iv" TEXT,
  ADD COLUMN IF NOT EXISTS "auth_tag" TEXT,
  ADD COLUMN IF NOT EXISTS "key_version" TEXT;

ALTER TABLE "intel_live_action_item" ALTER COLUMN "description" DROP NOT NULL;

-- ── intel_live_summary_card: title AND body are prose ──────────────────────────
-- card_type stays plaintext: it is a category, and the supporters/opponents split
-- matches on it, so encrypting it would break that read for sensitive sessions.
ALTER TABLE "intel_live_summary_card"
  ADD COLUMN IF NOT EXISTS "title_ciphertext" TEXT,
  ADD COLUMN IF NOT EXISTS "title_iv" TEXT,
  ADD COLUMN IF NOT EXISTS "title_auth_tag" TEXT,
  ADD COLUMN IF NOT EXISTS "title_key_version" TEXT,
  ADD COLUMN IF NOT EXISTS "body_ciphertext" TEXT,
  ADD COLUMN IF NOT EXISTS "body_iv" TEXT,
  ADD COLUMN IF NOT EXISTS "body_auth_tag" TEXT,
  ADD COLUMN IF NOT EXISTS "body_key_version" TEXT;

ALTER TABLE "intel_live_summary_card" ALTER COLUMN "title" DROP NOT NULL;
-- `body` was already nullable.

-- No backfill. Rows written before this migration are plaintext for non-sensitive
-- sessions (correct, unchanged) and simply absent for sensitive ones (they were
-- never persisted). Nothing can be recovered retroactively, and inventing rows
-- would fabricate intelligence that was never stored.
