/**
 * Typed runtime BRIDGE to the SHARED EXTERNAL @playwright/test package
 * (CleanUp1 §8; visual review round 8).
 *
 * Why this file exists — Playwright is NOT a dependency of this package or any
 * monorepo manifest, and no local `playwright install` is ever run. The runner
 * and its package live in an EXTERNAL prefix that is OUTSIDE every repository
 * ancestor (CI mount: /external; developer: C:/dev/.cleanup-playwright-runtime-…).
 *
 * A BARE `import '@playwright/test'` in playwright.config.ts or a spec file can
 * therefore never resolve on a fresh CI checkout: Playwright's own ESM resolve
 * hook (playwright/lib/common/index.js `resolveHook`) maps RELATIVE specifiers
 * and tsconfig `paths`, but delegates every bare specifier to Node's default
 * resolver, which performs the implicit ancestor walk the external prefix is
 * deliberately outside of. Root proved this natively on a cold Linux layout:
 *
 *   Error: Cannot find package '@playwright/test' imported from
 *          /source/apps/e2e/playwright.config.ts   (exit 1, ERR_MODULE_NOT_FOUND)
 *
 * The fix is a local bridge imported by RELATIVE path (always resolvable in both
 * layouts) that requires the external package from ITS OWN package path, so the
 * instance is the SAME one the launcher spawned — never an incidental ancestor
 * copy. Resolution is EXPLICIT and fail-closed (lib/playwright-runtime.mjs); an
 * explicit-but-unresolvable runtime is a hard error, never a silent fallback.
 *
 * Type surface: playwright-bridge.d.mts. tsc resolves its bare @playwright/test
 * against the explicit external baseUrl/paths generated by scripts/typecheck.mjs;
 * Playwright's runtime loader never reads the declaration file.
 */
import path from 'node:path';
import { createRequire } from 'node:module';
import { resolvePlaywrightRuntime } from './playwright-runtime.mjs';

const runtime = resolvePlaywrightRuntime();

// createRequire anchored at the EXTERNAL package's own package.json, so the
// specifier resolves to that exact instance (identity shared with the runner's
// test/fixture registry), not to any ancestor node_modules that may also exist.
const requireFromRuntime = createRequire(path.join(runtime.packageDir, 'package.json'));
const playwrightTest = requireFromRuntime('@playwright/test');

if (!playwrightTest || typeof playwrightTest.test !== 'function' || typeof playwrightTest.expect !== 'function') {
  throw new Error(
    `[playwright-bridge] @playwright/test at ${runtime.packageDir} did not expose test/expect ` +
      `(source=${runtime.source}); refusing to run with a malformed runtime`,
  );
}

export const test = playwrightTest.test;
export const expect = playwrightTest.expect;
export const defineConfig = playwrightTest.defineConfig;
export const devices = playwrightTest.devices;
export const chromium = playwrightTest.chromium;
export const firefox = playwrightTest.firefox;
export const webkit = playwrightTest.webkit;

// The resolved-runtime descriptor (source/packageDir/cli) is exported so a proof
// can assert the bridge bound the EXPLICIT external instance, not `implicit`.
export const playwrightRuntime = runtime;

export default playwrightTest;
