import { ServiceUnavailableException } from '@nestjs/common';
import { GenerationService } from '../src/generation/generation.service';
import type { PrismaService } from '../src/prisma/prisma.service';
import type { AiCredentialService } from '../src/generation/ai-credential.service';
import type { PeResolverService } from '../src/generation/pe-resolver.service';
import type { MeriV2FlagsService } from '../src/meriv2/meriv2-flags.service';
import type { MeriV2OrchestratorClient } from '../src/meriv2/meriv2-orchestrator.client';
import type { WorkspaceContextCompilerService } from '../src/generation/context-compiler.service';
import type { CollaboratorsService } from '../src/collaborators/collaborators.service';

/**
 * The write-back half of the orchestrator-generation contract: apps/workspace
 * remains the ONLY writer of ws_draft.config even when the section content was
 * reasoned by the MeriV2 orchestrator, not this service's own generateSection.
 */
describe('GenerationService.applyGeneratedSections', () => {
  function makeService(draft: unknown) {
    const updateSpy = jest.fn().mockResolvedValue(undefined);
    // The post-write refresh reads `.documents` for the "As generated" version
    // snapshot (persistGeneratedSections), so a non-null draft must carry a
    // documents array; the 404 test passes null and never reaches that path.
    const refreshed =
      draft && typeof draft === 'object'
        ? { documents: [], ...(draft as Record<string, unknown>) }
        : draft;
    const findFirstSpy = jest.fn().mockResolvedValue(refreshed);
    const prisma = {
      wsDraft: { findFirst: findFirstSpy, update: updateSpy },
      // Fire-and-forget "As generated" snapshot target (added to
      // persistGeneratedSections after this test was first written).
      wsDocVersion: { create: jest.fn().mockResolvedValue({}) },
    } as unknown as PrismaService;
    const service = new GenerationService(
      prisma,
      {} as AiCredentialService,
      {} as PeResolverService,
      {} as MeriV2FlagsService,
      {} as MeriV2OrchestratorClient,
      {} as WorkspaceContextCompilerService,
      {} as CollaboratorsService,
    );
    return { service, updateSpy, findFirstSpy };
  }

  it('404s when the draft is not found in the tenant', async () => {
    const { service } = makeService(null);
    await expect(
      service.applyGeneratedSections('tenant-1', 'draft-1', { sectionContent: { Summary: 'x' } }),
    ).rejects.toBeInstanceOf(ServiceUnavailableException);
  });

  it('merges sectionContent/sectionMeta/structuralWarnings into config, preserving other fields', async () => {
    const draft = {
      id: 'draft-1',
      config: { product: 'memo', client: 'Acme', sections: ['Summary', 'Ask'] },
    };
    const { service, updateSpy, findFirstSpy } = makeService(draft);

    await service.applyGeneratedSections('tenant-1', 'draft-1', {
      sectionContent: { Summary: '<p>Generated by MeriV2.</p>' },
      sectionMeta: { Summary: { status: 'review' } },
      structuralWarnings: [{ code: 'rdte_procurement_mismatch', peCode: '0207179F', message: 'x' }],
    });

    expect(updateSpy).toHaveBeenCalledWith({
      where: { id: 'draft-1' },
      data: {
        config: {
          product: 'memo',
          client: 'Acme',
          sections: ['Summary', 'Ask'],
          sectionContent: { Summary: '<p>Generated by MeriV2.</p>' },
          sectionMeta: { Summary: { status: 'review' } },
          structuralWarnings: [
            { code: 'rdte_procurement_mismatch', peCode: '0207179F', message: 'x' },
          ],
        },
      },
    });
    // Re-fetches the draft (tenant-scoped) after the write, with documents.
    expect(findFirstSpy).toHaveBeenLastCalledWith({
      where: { id: 'draft-1', tenantId: 'tenant-1' },
      include: { documents: { orderBy: { ordinal: 'asc' } } },
    });
  });

  it('defaults missing fields to the existing config values / empty, never crashes on a partial body', async () => {
    const draft = {
      id: 'draft-1',
      config: {
        product: 'memo',
        sectionContent: { Ask: 'existing ask text' },
        sectionMeta: { Ask: { status: 'draft' } },
      },
    };
    const { service, updateSpy } = makeService(draft);

    await service.applyGeneratedSections('tenant-1', 'draft-1', {});

    expect(updateSpy).toHaveBeenCalledWith({
      where: { id: 'draft-1' },
      data: {
        config: {
          product: 'memo',
          sectionContent: { Ask: 'existing ask text' },
          sectionMeta: { Ask: { status: 'draft' } },
          structuralWarnings: [],
        },
      },
    });
  });

  // An orchestrator-driven apply carries no provenance — it must NOT wipe the
  // "context used" snapshot a prior in-process generate-all captured (Phase 3.3).
  it('applyGeneratedSections preserves an existing contextProvenance (no provenance in body)', async () => {
    const prov = {
      generatedAt: '2026-07-12T00:00:00.000Z',
      contextItems: [{ id: 'ci-1', kind: 'free-text', label: 'ROI over feasibility' }],
      memoryFiles: [{ id: 'm-1', type: 'firm-soul', slug: 'firm', label: 'Firm Soul' }],
      linkedPeCodes: ['0603851F'],
    };
    const draft = { id: 'draft-1', config: { product: 'memo', contextProvenance: prov } };
    const { service, updateSpy } = makeService(draft);

    await service.applyGeneratedSections('tenant-1', 'draft-1', {
      sectionContent: { Summary: '<p>x</p>' },
    });

    const written = (updateSpy.mock.calls[0]![0] as { data: { config: Record<string, unknown> } })
      .data.config;
    expect(written.contextProvenance).toEqual(prov);
  });
});

describe('GenerationService.getContextUsed (Phase 3.3 "context used" panel)', () => {
  function makeService(draft: unknown) {
    const findFirstSpy = jest.fn().mockResolvedValue(draft);
    const prisma = {
      wsDraft: { findFirst: findFirstSpy },
    } as unknown as PrismaService;
    const service = new GenerationService(
      prisma,
      {} as AiCredentialService,
      {} as PeResolverService,
      {} as MeriV2FlagsService,
      {} as MeriV2OrchestratorClient,
      {} as WorkspaceContextCompilerService,
      {} as CollaboratorsService,
    );
    return { service, findFirstSpy };
  }

  it('404s when the draft is not found', async () => {
    const { service } = makeService(null);
    await expect(service.getContextUsed('t1', 'd1')).rejects.toBeInstanceOf(
      ServiceUnavailableException,
    );
  });

  it('returns null when the draft has no provenance (never generated)', async () => {
    const { service } = makeService({ config: { product: 'memo' } });
    expect(await service.getContextUsed('t1', 'd1')).toBeNull();
  });

  it('returns the stored provenance snapshot', async () => {
    const prov = {
      generatedAt: '2026-07-12T00:00:00.000Z',
      contextItems: [{ id: 'ci-1', kind: 'bill', label: 'H.R. 8800' }],
      memoryFiles: [{ id: 'm-1', type: 'user-voice', slug: 'me', label: 'My Writing Style' }],
      linkedPeCodes: ['0603851F'],
    };
    const { service } = makeService({ config: { contextProvenance: prov } });
    expect(await service.getContextUsed('t1', 'd1')).toEqual(prov);
  });

  it('shape-normalizes a partial/legacy provenance (never crashes the panel)', async () => {
    const { service } = makeService({ config: { contextProvenance: { contextItems: 'oops' } } });
    expect(await service.getContextUsed('t1', 'd1')).toEqual({
      generatedAt: '',
      contextItems: [],
      memoryFiles: [],
      linkedPeCodes: [],
    });
  });
});

describe('GenerationService.runGroundingAuditor (Phase 3.1 — reuses the shared Phase 2 auditor)', () => {
  function makeService() {
    const prisma = { wsDraft: {} } as unknown as PrismaService;
    return new GenerationService(
      prisma,
      {} as AiCredentialService,
      {} as PeResolverService,
      {} as MeriV2FlagsService,
      {} as MeriV2OrchestratorClient,
      {} as WorkspaceContextCompilerService,
      {} as CollaboratorsService,
    );
  }
  // Authoritative PE: FY27 enacted ($112.9M) is ABOVE the request ($72.1M) — an
  // INCREASE. A section calling it a "cut" is the reversed-direction class (D4)
  // that shipped as a client incident elsewhere; the shared auditor must catch it.
  const authPes = [
    {
      peCode: '0603851F',
      title: 'Test PE',
      description: null,
      service: null,
      appropriationType: null,
      budgetActivity: null,
      budgetActivityName: null,
      status: null,
      years: [{ fy: 2027, request: 72.1, enacted: 112.9, hascMark: null, sascMark: null }],
      people: [],
      contractors: [],
      bills: [],
    },
  ];

  it('flags a reversed funding-direction claim (D4) against the linked-PE evidence', () => {
    const svc = makeService();
    const sectionContent = {
      Summary: '<p>PE 0603851F funding was cut this cycle, well below the request.</p>',
    };
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const findings = (svc as any).runGroundingAuditor(sectionContent, authPes as any);
    expect(findings.some((f: { check: string }) => f.check === 'D4')).toBe(true);
  });

  it('does NOT flag a correctly-stated increase (no false positive)', () => {
    const svc = makeService();
    const sectionContent = {
      Summary: '<p>PE 0603851F funding rose this cycle, above the request.</p>',
    };
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const findings = (svc as any).runGroundingAuditor(sectionContent, authPes as any);
    expect(findings.some((f: { check: string }) => f.check === 'D4')).toBe(false);
  });

  it('returns [] when there is no generated text (best-effort, never throws)', () => {
    const svc = makeService();
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    expect((svc as any).runGroundingAuditor({}, [])).toEqual([]);
  });
});
