/**
 * WS-22 R1 — the generated document body must be built by merging the admitted
 * generated sections into the EXACT snapshot the body's compare-and-set compares.
 *
 * WHY THIS FILE EXISTS
 * The result path of `applyIntakeAdmission` used to read the draft's
 * section-content map BEFORE `writeDraftSections` read the fresh snapshot its
 * `updateMany` compares against. A save landing in that window was compared
 * against bytes that already contained it (so the compare-and-set PASSED) while
 * the payload was based on the older map (so the save was silently replaced).
 * The fix reads that map once, inside `writeDraftSections`, and merges the
 * admitted sections into the very snapshot that forms the comparison.
 *
 * These cases drive the REAL `GenerationRunWorkerService` and
 * `NativeIntakeAdapter` through the whole claim → admission → result path on the
 * same authoritative fixture shape `native-intake.spec.ts` uses, and assert the
 * ACTUAL `wsDraft.updateMany` predicate and payload the production code issued:
 *   * the compared bytes and the payload base are the same bytes (the result
 *     path performs exactly ONE draft read between the request-identity write
 *     and the body write);
 *   * every entry that is not an admitted generated section survives exactly —
 *     unrelated human content, a previously generated section, the draft's own
 *     declared section order, unrelated config, and the retained native request
 *     binding;
 *   * a save that lands AFTER that read fails the comparison, so the body is
 *     REFUSED (nothing is reported as landed) and the run stays resumable with
 *     the human's bytes and the retained request intact.
 *
 * External seams mocked at the same boundaries as `native-intake.spec.ts`:
 *   * `PrismaService`      — the durable rows and the atomic lease claim;
 *   * `CollaboratorsService` — the current-access owner;
 *   * `VersionsService`    — the as-generated snapshot;
 *   * `GenerationService`   — asserted NEVER to be consulted (no legacy provider);
 *   * the native owner      — a recording `NativeGenerationTurnPort` (no network).
 */
