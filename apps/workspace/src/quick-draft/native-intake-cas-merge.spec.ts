/** The recorded write that carried the admitted document body. */
const bodyWrite = (prisma: FakePrisma) => prisma.draftWrites[prisma.draftWrites.length - 1]!;
const comparedConfigOf = (write: DraftWriteRecord) =>
  write.where.config.equals as Record<string, unknown>;
