-- Final closeout: make duplicate-active-evidence rejection DETERMINISTIC for
-- the seven reviewer-entered, award-bearing relationship types.
--
-- DistrictNexusRelationshipsService.assertNoDuplicate does a findFirst and then
-- a create. That is check-then-act: two concurrent admin submits (a
-- double-submit, a client retry, or two reviewers on the same award) can both
-- pass the probe and both insert, producing two active claims on the same
-- federal obligation. The closeout contract requires the rejection to be
-- deterministic, which only a database constraint can deliver.
--
-- Why this is NOT expressible as a Prisma @@unique (unlike
-- client_grant_nexus_producer_unique_idx, which is):
--
--   1. facility_id is nullable, and Postgres treats NULLs as DISTINCT in a
--      unique index — two rows differing only by a NULL facility_id would not
--      collide, which is exactly the duplicate we need to stop. Hence the
--      COALESCE to a sentinel uuid.
--   2. It must be PARTIAL. A rejected row is retained history (rejection is
--      soft state, never a delete), so re-entering a previously rejected claim
--      is legitimate and must not collide. `assertNoDuplicate` already excludes
--      `verification_status = 'rejected'`; the index mirrors that predicate
--      exactly so the two can never disagree.
--
-- Prisma cannot declare either property, so this stays raw SQL — the same
-- precedent as faa_recipient_name_trgm_idx.
--
-- SAFETY: the predicate indexes only rows with a non-null assistance_award_id.
-- Every client_grant_nexus row in capiro-dev today is an 'opportunity_candidate'
-- produced by generate-grant-opportunity-candidates, which sets
-- grant_opportunity_id and leaves assistance_award_id NULL. So this index covers
-- ZERO existing rows and cannot fail on pre-existing duplicates. The table holds
-- single digits of rows, so a plain (non-CONCURRENTLY) build is instant and
-- takes no meaningful lock.
--
-- The sentinel uuid is the all-zero uuid, which is not a valid
-- client_facilities.id (they are generated by uuid()), so it cannot collide
-- with a real facility.
CREATE UNIQUE INDEX IF NOT EXISTS "client_grant_nexus_manual_award_unique_idx"
  ON "client_grant_nexus" (
    "tenant_id",
    "client_id",
    "assistance_award_id",
    "relationship_type",
    "evidence_source_type",
    COALESCE("facility_id", '00000000-0000-0000-0000-000000000000'::uuid)
  )
  WHERE "assistance_award_id" IS NOT NULL
    AND "verification_status" <> 'rejected';
