import {
  computeMatterClue,
  titleTokens,
  tokenOverlap,
  TITLE_OVERLAP_THRESHOLD,
  type MatterType,
} from './client-advocacy-matter.helpers.js';

interface OpenMatterRow {
  id: string;
  title: string;
  externalKey: string;
}

export interface AdvocacyMatterSummary {
  id: string;
  title: string;
  matterType: MatterType | string;
  status: string;
  summary: string | null;
  primaryPeCode: string | null;
  primaryBillId: string | null;
  externalKey: string;
  autoGenerated: boolean;
  openedAt: string | null;
  lastActivityAt: string | null;
  recordCount: number;
  outcomeCount: number;
  linkCount: number;
  createdAt: string;
  updatedAt: string;
}

export interface AdvocacyMatterDetail extends AdvocacyMatterSummary {
  records: Array<{
    id: string;
    recordType: string;
    title: string;
    summary: string | null;
    activityDate: string | null;
    status: string | null;
    outcome: string | null;
    sourceType: string;
    sourceId: string | null;
    sourceUrl: string | null;
    evidenceClass: string;
    confidence: number;
    metadata: Record<string, unknown>;
    createdAt: string;
    /** True once a human has reassigned/detached/rejected this record — automatic
     *  clustering will not touch it again. */
    matterLocked: boolean;
  }>;
  links: Array<{
    id: string;
    linkType: string;
    linkKey: string;
    label: string | null;
    metadata: Record<string, unknown>;
  }>;
}

/**
 * Advocacy Matter: the grouping abstraction over Advocacy History.
 *
 * `client_advocacy_record` (PR #1246) is the durable per-item ledger — one
 * row per LDA filing activity, client submission, or private meeting/email
 * candidate. That is necessary but not sufficient: the product asks for a
 * coherent institutional history ("what has this client advocated for"),
 * not a flat timeline of unconnected records. This service assigns every
 * advocacy record to a Matter (clustering by Program Element, bill, LDA
 * issue code, or normalized title — see client-advocacy-matter.helpers.ts),
 * links non-record institutional-history objects (Program Elements, bills,
 * outcome events) that don't have their own client_advocacy_record row, and
 * serves the read APIs the CRM surface renders.
 *
 * Clustering runs idempotently: `assignMatterForRecord` can be called every
 * time a record is applied (including on a re-run of Fill with Meri) and
 * will resolve to the SAME Matter for the same clue without creating
 * duplicates, because the clue's `key` is unique-constrained per client.
 */
@Injectable()
export class ClientAdvocacyMatterService {
  private readonly logger = new Logger(ClientAdvocacyMatterService.name);

  constructor(private readonly prisma: PrismaService) {}

  /**
   * Resolves (creating if necessary) the Matter a just-applied advocacy
   * record belongs to, and attaches the record to it. Called from
   * `ClientProfileFillCompletionService.applyAdvocacyRecord` right after
   * the record itself is upserted, inside the same tenant transaction.
   *
   * Respects `matter_locked`: once a human has reassigned, detached, or
   * rejected ("not advocacy") a record via the correction UX, this method
   * is a no-op for that record on every subsequent Fill with Meri re-run.
   * Human corrections are authoritative over automatic clustering (product
   * spec section 6) — without this check, re-running the same finding would
   * silently undo the correction the next time the external_key upserts.
   */
  async assignMatterForRecord(
    ctx: TenantContext,
    clientId: string,
    recordExternalKey: string,
    record: { recordType: string; title: string; metadata: Record<string, unknown>; activityDate: string | null },
  ): Promise<string | null> {
    const clue = computeMatterClue({
      recordType: record.recordType,
      title: record.title,
      metadata: record.metadata,
    });

    return this.prisma.withTenant(ctx.tenantId, async (tx) => {
      const existing = await tx.$queryRawUnsafe<Array<{ matterId: string | null; locked: boolean }>>(
        `SELECT matter_id AS "matterId", matter_locked AS locked
           FROM client_advocacy_record
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND external_key = $3
          LIMIT 1`,
        ctx.tenantId,
        clientId,
        recordExternalKey,
      );
      if (existing[0]?.locked) {
        // A human already decided this record's Matter (or explicitly
        // detached it, leaving matterId null while locked) — leave it alone.
        return existing[0].matterId;
      }

      const matterId = await this.resolveMatterId(tx, ctx.tenantId, clientId, clue, record.title);
      await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_record
            SET matter_id = $4::uuid
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND external_key = $3
            AND (matter_id IS NULL OR matter_id <> $4::uuid)`,
        ctx.tenantId,
        clientId,
        recordExternalKey,
        matterId,
      );
      await this.touchMatterActivity(tx, ctx.tenantId, matterId, record.activityDate);
      return matterId;
    });
  }

  /**
   * Resolves the Matter id for a clustering clue, creating a new Matter row
   * if none matches. Exact clue-key match first (idempotent re-runs);
   * otherwise fuzzy title-overlap against the client's OPEN auto-generated
   * matters (so restated asks with slightly different wording still fold
   * together); otherwise a brand-new Matter.
   *
   * `tx` must already be inside a `withTenant`/`withSystem` transaction —
   * this method does not open its own.
   */
  private async resolveMatterId(
    tx: { $queryRawUnsafe: <T>(query: string, ...args: unknown[]) => Promise<T>; $executeRawUnsafe: (query: string, ...args: unknown[]) => Promise<unknown> },
    tenantId: string,
    clientId: string,
    clue: { key: string; matterType: MatterType; title: string; primaryPeCode: string | null; primaryBillId: string | null },
    fallbackTitle: string,
  ): Promise<string> {
    const exact = await tx.$queryRawUnsafe<Array<{ id: string }>>(
      `SELECT id FROM client_advocacy_matter
        WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND external_key = $3
        LIMIT 1`,
      tenantId,
      clientId,
      clue.key,
    );
    if (exact[0]?.id) return exact[0].id;

    // Fuzzy fallback only applies to auto-clustered ("auto:...") clues —
    // PE/bill/issue-code clues are already maximally specific and must not
    // be fuzzy-merged into an unrelated Matter.
    if (clue.key.startsWith('auto:')) {
      const open = await tx.$queryRawUnsafe<OpenMatterRow[]>(
        `SELECT id, title, external_key AS "externalKey"
           FROM client_advocacy_matter
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid
            AND auto_generated = true AND status IN ('open', 'monitoring')
          ORDER BY last_activity_at DESC NULLS LAST, created_at DESC
          LIMIT 100`,
        tenantId,
        clientId,
      );
      const candidateTokens = titleTokens(fallbackTitle || clue.title);
      let best: { id: string; score: number } | null = null;
      for (const row of open) {
        const score = tokenOverlap(candidateTokens, titleTokens(row.title));
        if (score >= TITLE_OVERLAP_THRESHOLD && (!best || score > best.score)) {
          best = { id: row.id, score };
        }
      }
      if (best) return best.id;
    }

    const inserted = await tx.$queryRawUnsafe<Array<{ id: string }>>(
      `INSERT INTO client_advocacy_matter
         (tenant_id, client_id, title, matter_type, status, external_key,
          auto_generated, primary_pe_code, primary_bill_id, opened_at)
       VALUES ($1::uuid, $2::uuid, $3, $4, 'open', $5, true, $6, $7, now())
       ON CONFLICT (tenant_id, client_id, external_key) DO UPDATE
         SET updated_at = now()
       RETURNING id`,
      tenantId,
      clientId,
      clue.title || fallbackTitle || 'Advocacy matter',
      clue.matterType,
      clue.key,
      clue.primaryPeCode,
      clue.primaryBillId,
    );
    return inserted[0]!.id;
  }

  private async touchMatterActivity(
    tx: { $executeRawUnsafe: (query: string, ...args: unknown[]) => Promise<unknown> },
    tenantId: string,
    matterId: string,
    activityDate: string | null,
  ): Promise<void> {
    await tx.$executeRawUnsafe(
      `UPDATE client_advocacy_matter
          SET last_activity_at = GREATEST(
                COALESCE(last_activity_at, 'epoch'::timestamptz),
                COALESCE($3::timestamptz, now())
              ),
              updated_at = now()
        WHERE tenant_id = $1::uuid AND id = $2::uuid`,
      tenantId,
      matterId,
      activityDate,
    );
  }

  /**
   * Links a non-record institutional-history object (Program Element,
   * bill, or outcome event) to an existing Matter. Used when an outcome or
   * a PE/bill recommendation should surface inside a Matter's history even
   * though it never became its own `client_advocacy_record` row.
   */
  async linkToMatter(
    ctx: TenantContext,
    matterId: string,
    input: { linkType: 'program_element' | 'bill' | 'outcome_event' | 'finding'; linkKey: string; label?: string | null; metadata?: Record<string, unknown> },
  ): Promise<void> {
    await this.prisma.withTenant(ctx.tenantId, (tx) =>
      tx.$executeRawUnsafe(
        `INSERT INTO client_advocacy_matter_link
           (tenant_id, matter_id, link_type, link_key, label, metadata_jsonb, created_by_user_id)
         VALUES ($1::uuid, $2::uuid, $3, $4, $5, $6::jsonb, $7::uuid)
         ON CONFLICT (matter_id, link_type, link_key) DO UPDATE
           SET label = COALESCE(EXCLUDED.label, client_advocacy_matter_link.label),
               metadata_jsonb = client_advocacy_matter_link.metadata_jsonb || EXCLUDED.metadata_jsonb`,
        ctx.tenantId,
        matterId,
        input.linkType,
        input.linkKey,
        input.label ?? null,
        JSON.stringify(input.metadata ?? {}),
        ctx.userId,
      ),
    );
  }

  /** Matters for a client, newest activity first, with rollup counts. */
  async listMatters(ctx: TenantContext, clientId: string): Promise<AdvocacyMatterSummary[]> {
    await this.assertClient(ctx, clientId);
    const rows = await this.prisma.withTenant(ctx.tenantId, (tx) =>
      tx.$queryRawUnsafe<
        Array<{
          id: string;
          title: string;
          matterType: string;
          status: string;
          summary: string | null;
          primaryPeCode: string | null;
          primaryBillId: string | null;
          externalKey: string;
          autoGenerated: boolean;
          openedAt: Date | null;
          lastActivityAt: Date | null;
          createdAt: Date;
          updatedAt: Date;
          recordCount: number;
          outcomeCount: number;
          linkCount: number;
        }>
      >(
        `SELECT m.id, m.title, m.matter_type AS "matterType", m.status,
                m.summary, m.primary_pe_code AS "primaryPeCode",
                m.primary_bill_id AS "primaryBillId",
                m.external_key AS "externalKey", m.auto_generated AS "autoGenerated",
                m.opened_at AS "openedAt", m.last_activity_at AS "lastActivityAt",
                m.created_at AS "createdAt", m.updated_at AS "updatedAt",
                COALESCE(rc.count, 0)::int AS "recordCount",
                COALESCE(rc.outcome_count, 0)::int AS "outcomeCount",
                COALESCE(lc.count, 0)::int AS "linkCount"
           FROM client_advocacy_matter m
           LEFT JOIN (
             SELECT matter_id,
                    COUNT(*) AS count,
                    COUNT(*) FILTER (WHERE outcome IS NOT NULL) AS outcome_count
               FROM client_advocacy_record
              WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND matter_id IS NOT NULL AND not_advocacy = false
              GROUP BY matter_id
           ) rc ON rc.matter_id = m.id
           LEFT JOIN (
             SELECT matter_id, COUNT(*) AS count
               FROM client_advocacy_matter_link
              WHERE tenant_id = $1::uuid
              GROUP BY matter_id
           ) lc ON lc.matter_id = m.id
          WHERE m.tenant_id = $1::uuid AND m.client_id = $2::uuid
          ORDER BY m.last_activity_at DESC NULLS LAST, m.created_at DESC`,
        ctx.tenantId,
        clientId,
      ),
    );
    return rows.map((row) => ({
      id: row.id,
      title: row.title,
      matterType: row.matterType,
      status: row.status,
      summary: row.summary,
      primaryPeCode: row.primaryPeCode,
      primaryBillId: row.primaryBillId,
      externalKey: row.externalKey,
      autoGenerated: row.autoGenerated,
      openedAt: row.openedAt?.toISOString() ?? null,
      lastActivityAt: row.lastActivityAt?.toISOString() ?? null,
      recordCount: row.recordCount,
      outcomeCount: row.outcomeCount,
      linkCount: row.linkCount,
      createdAt: row.createdAt.toISOString(),
      updatedAt: row.updatedAt.toISOString(),
    }));
  }

  /** One Matter with its full record and link roll-up, for the Matter detail drawer. */
  async getMatter(ctx: TenantContext, clientId: string, matterId: string): Promise<AdvocacyMatterDetail> {
    await this.assertClient(ctx, clientId);
    const result = await this.prisma.withTenant(ctx.tenantId, async (tx) => {
      const matterRows = await tx.$queryRawUnsafe<
        Array<{
          id: string;
          title: string;
          matterType: string;
          status: string;
          summary: string | null;
          primaryPeCode: string | null;
          primaryBillId: string | null;
          externalKey: string;
          autoGenerated: boolean;
          openedAt: Date | null;
          lastActivityAt: Date | null;
          createdAt: Date;
          updatedAt: Date;
        }>
      >(
        `SELECT id, title, matter_type AS "matterType", status, summary,
                primary_pe_code AS "primaryPeCode", primary_bill_id AS "primaryBillId",
                external_key AS "externalKey", auto_generated AS "autoGenerated",
                opened_at AS "openedAt", last_activity_at AS "lastActivityAt",
                created_at AS "createdAt", updated_at AS "updatedAt"
           FROM client_advocacy_matter
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid
          LIMIT 1`,
        ctx.tenantId,
        clientId,
        matterId,
      );
      const matter = matterRows[0];
      if (!matter) return null;

      const records = await tx.$queryRawUnsafe<
        Array<{
          id: string;
          recordType: string;
          title: string;
          summary: string | null;
          activityDate: Date | null;
          status: string | null;
          outcome: string | null;
          sourceType: string;
          sourceId: string | null;
          sourceUrl: string | null;
          evidenceClass: string;
          confidence: number;
          metadata: unknown;
          createdAt: Date;
          matterLocked: boolean;
        }>
      >(
        `SELECT id, record_type AS "recordType", title, summary,
                activity_date AS "activityDate", status, outcome,
                source_type AS "sourceType", source_id AS "sourceId",
                source_url AS "sourceUrl", evidence_class AS "evidenceClass",
                confidence, metadata_jsonb AS metadata, created_at AS "createdAt",
                matter_locked AS "matterLocked"
           FROM client_advocacy_record
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND matter_id = $3::uuid AND not_advocacy = false
          ORDER BY activity_date DESC NULLS LAST, created_at DESC`,
        ctx.tenantId,
        clientId,
        matterId,
      );

      const links = await tx.$queryRawUnsafe<
        Array<{ id: string; linkType: string; linkKey: string; label: string | null; metadata: unknown }>
      >(
        `SELECT id, link_type AS "linkType", link_key AS "linkKey", label, metadata_jsonb AS metadata
           FROM client_advocacy_matter_link
          WHERE tenant_id = $1::uuid AND matter_id = $2::uuid
          ORDER BY created_at DESC`,
        ctx.tenantId,
        matterId,
      );

      return { matter, records, links };
    });

    if (!result) throw new NotFoundException('Advocacy matter not found');
    const { matter, records, links } = result;
    const recordCount = records.length;
    const outcomeCount = records.filter((r) => r.outcome != null).length;

    return {
      id: matter.id,
      title: matter.title,
      matterType: matter.matterType,
      status: matter.status,
      summary: matter.summary,
      primaryPeCode: matter.primaryPeCode,
      primaryBillId: matter.primaryBillId,
      externalKey: matter.externalKey,
      autoGenerated: matter.autoGenerated,
      openedAt: matter.openedAt?.toISOString() ?? null,
      lastActivityAt: matter.lastActivityAt?.toISOString() ?? null,
      recordCount,
      outcomeCount,
      linkCount: links.length,
      createdAt: matter.createdAt.toISOString(),
      updatedAt: matter.updatedAt.toISOString(),
      records: records.map((r) => ({
        id: r.id,
        recordType: r.recordType,
        title: r.title,
        summary: r.summary,
        activityDate: r.activityDate?.toISOString() ?? null,
        status: r.status,
        outcome: r.outcome,
        sourceType: r.sourceType,
        sourceId: r.sourceId,
        sourceUrl: r.sourceUrl,
        evidenceClass: r.evidenceClass,
        confidence: Number(r.confidence),
        metadata: asRecord(r.metadata),
        createdAt: r.createdAt.toISOString(),
        matterLocked: r.matterLocked,
      })),
      links: links.map((l) => ({
        id: l.id,
        linkType: l.linkType,
        linkKey: l.linkKey,
        label: l.label,
        metadata: asRecord(l.metadata),
      })),
    };
  }

  /**
   * Manually create a new Matter (not auto-clustered). Used by the
   * correction UX's "Create new Matter" action (reassigning a record into a
   * brand-new Matter rather than an existing one) and by Fill review's
   * "Create Matter" action for a proposed activity that doesn't fit any
   * existing Matter.
   */
  async createMatter(
    ctx: TenantContext,
    clientId: string,
    input: { title: string; matterType?: string; summary?: string | null },
  ): Promise<string> {
    await this.assertClient(ctx, clientId);
    const externalKey = `manual:${randomUUID()}`;
    const inserted = await this.prisma.withTenant(ctx.tenantId, (tx) =>
      tx.$queryRawUnsafe<Array<{ id: string }>>(
        `INSERT INTO client_advocacy_matter
           (tenant_id, client_id, title, matter_type, status, summary, external_key,
            auto_generated, opened_at, created_by_user_id)
         VALUES ($1::uuid, $2::uuid, $3, $4, 'planning', $5, $6, false, now(), $7::uuid)
         RETURNING id`,
        ctx.tenantId,
        clientId,
        input.title,
        input.matterType ?? 'other',
        input.summary ?? null,
        externalKey,
        ctx.userId,
      ),
    );
    return inserted[0]!.id;
  }

  /**
   * Manually edit a Matter's product-facing fields (title/status/summary).
   * A Matter created automatically stays `autoGenerated: true` even after a
   * manual edit — that flag tracks provenance of the grouping decision, not
   * whether a human has since touched it.
   *
   * Status transitions into `successful` / `partially_successful` /
   * `unsuccessful` require explicit evidence: either the Matter already has
   * at least one linked `outcome_event`, or the caller passes
   * `confirmOutcome: true` (an explicit human confirmation from the Matter
   * detail UI). This is the enforcement point for product spec section 7 —
   * "Meri must not automatically set successful" and "should require
   * explicit evidence or human confirmation" — Meri only ever calls
   * `linkToMatter`/`assignMatterForRecord`, never `updateMatter`, so this
   * path is human-only by construction, but the evidence/confirmation
   * requirement still applies to prevent a careless one-click status change.
   * `outcome_observed` has no such requirement — it means "something
   * happened," not "the ask succeeded," and does not require confirmation.
   */
  async updateMatter(
    ctx: TenantContext,
    clientId: string,
    matterId: string,
    input: { title?: string; status?: string; summary?: string | null; confirmOutcome?: boolean },
  ): Promise<void> {
    await this.assertClient(ctx, clientId);
    const OUTCOME_STATUSES = new Set(['successful', 'partially_successful', 'unsuccessful']);
    await this.prisma.withTenant(ctx.tenantId, async (tx) => {
      let confirmOutcomeNow = false;
      if (input.status && OUTCOME_STATUSES.has(input.status)) {
        const evidence = await tx.$queryRawUnsafe<Array<{ count: number }>>(
          `SELECT COUNT(*)::int AS count FROM client_advocacy_matter_link
            WHERE tenant_id = $1::uuid AND matter_id = $2::uuid AND link_type = 'outcome_event'`,
          ctx.tenantId,
          matterId,
        );
        const hasOutcomeEvidence = (evidence[0]?.count ?? 0) > 0;
        if (!hasOutcomeEvidence && input.confirmOutcome !== true) {
          throw new BadRequestException(
            `Setting status to "${input.status}" requires either a linked outcome event or explicit human confirmation (confirmOutcome: true)`,
          );
        }
        confirmOutcomeNow = true;
      }

      const changed = await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_matter
            SET title = COALESCE($4, title),
                status = COALESCE($5, status),
                summary = CASE WHEN $6::boolean THEN $7 ELSE summary END,
                outcome_confirmed_by_user_id = CASE WHEN $8::boolean THEN $9::uuid ELSE outcome_confirmed_by_user_id END,
                outcome_confirmed_at = CASE WHEN $8::boolean THEN now() ELSE outcome_confirmed_at END,
                updated_at = now()
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid`,
        ctx.tenantId,
        clientId,
        matterId,
        asString(input.title),
        asString(input.status),
        input.summary !== undefined,
        input.summary ?? null,
        confirmOutcomeNow,
        ctx.userId,
      );
      if (Number(changed) !== 1) throw new NotFoundException('Advocacy matter not found');
    });
  }

  /**
   * Reassign a single advocacy record to a different (existing) Matter.
   * Locks the record so a later Fill with Meri re-run cannot silently move
   * it back — see `assignMatterForRecord`'s `matter_locked` check.
   */
  async reassignRecord(
    ctx: TenantContext,
    clientId: string,
    recordId: string,
    targetMatterId: string,
  ): Promise<void> {
    await this.assertClient(ctx, clientId);
    await this.prisma.withTenant(ctx.tenantId, async (tx) => {
      const targetExists = await tx.$queryRawUnsafe<Array<{ id: string }>>(
        `SELECT id FROM client_advocacy_matter WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid`,
        ctx.tenantId,
        clientId,
        targetMatterId,
      );
      if (targetExists.length === 0) throw new NotFoundException('Target advocacy matter not found');

      const sourceMatterRow = await tx.$queryRawUnsafe<Array<{ matterId: string | null }>>(
        `SELECT matter_id AS "matterId" FROM client_advocacy_record
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid`,
        ctx.tenantId,
        clientId,
        recordId,
      );
      if (sourceMatterRow.length === 0) throw new NotFoundException('Advocacy record not found');
      const sourceMatterId = sourceMatterRow[0]!.matterId;

      const changed = await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_record
            SET matter_id = $4::uuid, matter_locked = true, not_advocacy = false,
                reviewed_by_user_id = $5::uuid, reviewed_at = now(), updated_at = now()
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid`,
        ctx.tenantId,
        clientId,
        recordId,
        targetMatterId,
        ctx.userId,
      );
      this.assertOneRowChanged(changed, 'Advocacy record not found');

      await this.touchMatterActivity(tx, ctx.tenantId, targetMatterId, null);
      if (sourceMatterId && sourceMatterId !== targetMatterId) {
        await this.touchMatterActivity(tx, ctx.tenantId, sourceMatterId, null);
      }
    });
  }

  /**
   * Detach a record from its Matter (falsely associated). The record is
   * NOT deleted — it becomes unassigned (`matter_id = NULL`) and locked so
   * automatic clustering does not immediately re-cluster it right back in.
   */
  async detachRecord(ctx: TenantContext, clientId: string, recordId: string): Promise<void> {
    await this.assertClient(ctx, clientId);
    await this.prisma.withTenant(ctx.tenantId, async (tx) => {
      const changed = await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_record
            SET matter_id = NULL, matter_locked = true,
                reviewed_by_user_id = $4::uuid, reviewed_at = now(), updated_at = now()
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid`,
        ctx.tenantId,
        clientId,
        recordId,
        ctx.userId,
      );
      this.assertOneRowChanged(changed, 'Advocacy record not found');
    });
  }

  /**
   * Mark a proposed advocacy activity "Not advocacy" — a human rejection.
   * The record stays in the table (audit trail: who rejected it, when, and
   * what it originally claimed) but is excluded from Matter rollups and
   * detail record lists (see `listMatters`/`getMatter` filtering) and from
   * the Timeline. Also detaches it from any Matter and locks it, so a later
   * identical finding from Fill with Meri is not resurrected as a duplicate
   * (product spec section 26).
   */
  async markRecordNotAdvocacy(
    ctx: TenantContext,
    clientId: string,
    recordId: string,
    reason?: string | null,
  ): Promise<void> {
    await this.assertClient(ctx, clientId);
    await this.prisma.withTenant(ctx.tenantId, async (tx) => {
      const changed = await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_record
            SET not_advocacy = true, not_advocacy_reason = $4, matter_id = NULL, matter_locked = true,
                reviewed_by_user_id = $5::uuid, reviewed_at = now(), updated_at = now()
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id = $3::uuid`,
        ctx.tenantId,
        clientId,
        recordId,
        reason ?? null,
        ctx.userId,
      );
      this.assertOneRowChanged(changed, 'Advocacy record not found');
    });
  }

  /**
   * Manually merge `sourceMatterId` into `targetMatterId`: reassigns every
   * advocacy record and link, then deletes the now-empty source Matter.
   * Exposed for the case the automatic clustering under- or over-splits and
   * a human wants to correct it — see the "do not ship only a flat
   * timeline" product requirement; merging is the escape hatch for
   * imperfect auto-clustering rather than a promise the algorithm is exact.
   */
  async mergeMatters(
    ctx: TenantContext,
    clientId: string,
    targetMatterId: string,
    sourceMatterId: string,
  ): Promise<void> {
    if (targetMatterId === sourceMatterId) return;
    await this.assertClient(ctx, clientId);
    await this.prisma.withTenant(ctx.tenantId, async (tx) => {
      const targets = await tx.$queryRawUnsafe<Array<{ id: string }>>(
        `SELECT id FROM client_advocacy_matter
          WHERE tenant_id = $1::uuid AND client_id = $2::uuid AND id IN ($3::uuid, $4::uuid)`,
        ctx.tenantId,
        clientId,
        targetMatterId,
        sourceMatterId,
      );
      if (targets.length !== 2) throw new NotFoundException('Advocacy matter not found');

      await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_record SET matter_id = $3::uuid, updated_at = now()
          WHERE tenant_id = $1::uuid AND matter_id = $2::uuid`,
        ctx.tenantId,
        sourceMatterId,
        targetMatterId,
      );
      // Links are matter-scoped-unique on (matter_id, link_type, link_key);
      // a link already present on the target loses the source's duplicate.
      await tx.$executeRawUnsafe(
        `INSERT INTO client_advocacy_matter_link (tenant_id, matter_id, link_type, link_key, label, metadata_jsonb, created_by_user_id)
         SELECT tenant_id, $3::uuid, link_type, link_key, label, metadata_jsonb, created_by_user_id
           FROM client_advocacy_matter_link
          WHERE tenant_id = $1::uuid AND matter_id = $2::uuid
         ON CONFLICT (matter_id, link_type, link_key) DO NOTHING`,
        ctx.tenantId,
        sourceMatterId,
        targetMatterId,
      );
      await tx.$executeRawUnsafe(
        `UPDATE client_advocacy_matter SET last_activity_at = GREATEST(
              COALESCE((SELECT last_activity_at FROM client_advocacy_matter WHERE id = $2::uuid), 'epoch'::timestamptz),
              COALESCE(last_activity_at, 'epoch'::timestamptz)
            ), updated_at = now()
          WHERE tenant_id = $1::uuid AND id = $3::uuid`,
        ctx.tenantId,
        sourceMatterId,
        targetMatterId,
      );
      await tx.$executeRawUnsafe(
        `DELETE FROM client_advocacy_matter WHERE tenant_id = $1::uuid AND id = $2::uuid`,
        ctx.tenantId,
        sourceMatterId,
      );
    });
  }

  private async assertClient(ctx: TenantContext, clientId: string): Promise<void> {
    const client = await this.prisma.withTenant(ctx.tenantId, (tx) =>
      tx.client.findFirst({
        where: { id: clientId, tenantId: ctx.tenantId, status: { not: 'archived' } },
        select: { id: true },
      }),
    );
    if (!client) throw new NotFoundException('Client not found');
    this.logger.debug(`Advocacy matter access for client ${clientId}`);
  }

  /** Asserts an UPDATE affected exactly the one targeted row. Every record
   *  correction mutation (reassign/detach/not-advocacy/update) is scoped by
   *  primary key, so anything other than exactly 1 means the row didn't
   *  exist (or didn't belong to this tenant/client) — not a partial write. */
  private assertOneRowChanged(changed: unknown, notFoundMessage: string): void {
    if (Number(changed) !== 1) throw new NotFoundException(notFoundMessage);
  }
}
