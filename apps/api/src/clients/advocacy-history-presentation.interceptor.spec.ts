import {
  buildLdaRecordPresentation,
  presentAdvocacyHistoryResponse,
  presentIssueMatterTitle,
} from './advocacy-history-presentation.interceptor.js';

describe('Advocacy History LDA presentation', () => {
  const l3HarrisRecord = {
    id: 'record-1',
    recordType: 'federal_lobbying',
    sourceType: 'lda',
    title: '2021 first_quarter — DEF',
    summary:
      'National Defense Authorization Act of 2022, monitored issues related to GBSD and space propulsion technology. House and Senate Defense Appropriations Bills, as they relate to RDTE and Procurement.',
    status: 'Q1',
    metadata: {
      filingYear: 2021,
      filingPeriod: 'first_quarter',
      issueCodes: ['DEF'],
      activity: { general_issue_code: 'DEF' },
    },
  };

  test('turns the L3 Harris filing slug into an issue-first title and grounded summary', () => {
    const presentation = buildLdaRecordPresentation(l3HarrisRecord);

    expect(presentation.displayTitle).toBe('FY2022 NDAA — GBSD & Space Propulsion');
    expect(presentation.metadataLine).toBe('LDA · Q1 2021 · DEF');
    expect(presentation.displaySummary).toBe(
      'Monitored the FY2022 NDAA and House and Senate defense appropriations bills related to GBSD and space propulsion technology, as well as RDT&E and procurement. The filing does not state a specific ask or position.',
    );
    expect(presentation.topics).toEqual([
      'FY2022 NDAA',
      'GBSD',
      'Space Propulsion',
      'Defense Appropriations',
      'RDT&E',
      'Procurement',
    ]);
    expect(presentation.specificAskStated).toBe(false);
    expect(presentation.sourceTitle).toBe('2021 first_quarter — DEF');
    expect(presentation.sourceStatus).toBe('Q1');
  });

  test('does not append the no-ask note when the disclosure states a specific request', () => {
    const presentation = buildLdaRecordPresentation({
      ...l3HarrisRecord,
      summary: 'Requested an increase in RDT&E funding for the Sentinel program.',
    });

    expect(presentation.specificAskStated).toBe(true);
    expect(presentation.displaySummary).toBe(
      'Requested an increase in RDT&E funding for the Sentinel program.',
    );
    expect(presentation.displayTitle).toBe('Sentinel — Defense authorization & appropriations');
  });

  test('renames only generic issue-code matters', () => {
    expect(presentIssueMatterTitle('DEF lobbying activity', 'issue:DEF')).toBe(
      'Defense authorization & appropriations',
    );
    expect(presentIssueMatterTitle('Sentinel modernization', 'issue:DEF')).toBe(
      'Sentinel modernization',
    );
    expect(presentIssueMatterTitle('Human-authored Sentinel campaign', 'manual:123')).toBe(
      'Human-authored Sentinel campaign',
    );
  });

  test('presents existing detail records without rewriting the durable source values', () => {
    const original = {
      id: 'matter-1',
      title: 'DEF lobbying activity',
      externalKey: 'issue:DEF',
      autoGenerated: true,
      records: [l3HarrisRecord],
    };
    const presented = presentAdvocacyHistoryResponse(
      '/api/clients/client-1/advocacy-matters/matter-1',
      original,
    ) as {
      title: string;
      records: Array<{
        title: string;
        summary: string;
        status: string;
        metadata: { presentation: { sourceTitle: string; topics: string[] } };
      }>;
    };

    expect(presented.title).toBe('Defense authorization & appropriations');
    expect(presented.records[0]?.title).toBe('FY2022 NDAA — GBSD & Space Propulsion');
    expect(presented.records[0]?.status).toBe('LDA · Q1 2021 · DEF');
    expect(presented.records[0]?.metadata.presentation.sourceTitle).toBe(
      '2021 first_quarter — DEF',
    );
    expect(presented.records[0]?.metadata.presentation.topics).toContain('GBSD');

    expect(original.title).toBe('DEF lobbying activity');
    expect(original.records[0]?.title).toBe('2021 first_quarter — DEF');
  });

  test('does not overwrite a human-edited title on an auto-generated issue matter', () => {
    const presented = presentAdvocacyHistoryResponse(
      '/api/clients/client-1/advocacy-matters/matter-1',
      {
        title: 'Sentinel modernization',
        externalKey: 'issue:DEF',
        autoGenerated: true,
        records: [],
      },
    ) as { title: string };

    expect(presented.title).toBe('Sentinel modernization');
  });

  test('makes timeline rows readable even though the compact endpoint has no summary', () => {
    const presented = presentAdvocacyHistoryResponse(
      '/api/clients/client-1/advocacy-matters/timeline/',
      [
        {
          id: 'record-1',
          kind: 'record',
          subtype: 'federal_lobbying',
          title: '2021 first_quarter — DEF',
          matterTitle: 'DEF lobbying activity',
        },
      ],
    ) as Array<{ title: string; matterTitle: string }>;

    expect(presented[0]?.title).toBe('Defense authorization & appropriations — Q1 2021');
    expect(presented[0]?.matterTitle).toBe('Defense authorization & appropriations');
  });

  test('leaves non-LDA records and correlation suggestions unchanged', () => {
    const record = {
      recordType: 'client_submission',
      sourceType: 'client_submission',
      title: 'FY27 funding request',
    };
    const detail = presentAdvocacyHistoryResponse(
      '/api/clients/client-1/advocacy-matters/matter-1',
      { records: [record] },
    ) as { records: Array<typeof record> };
    expect(detail.records[0]).toEqual(record);

    const suggestions = [{ title: 'Final rule', documentNumber: '2026-1234' }];
    expect(
      presentAdvocacyHistoryResponse(
        '/api/clients/client-1/advocacy-matters/matter-1/federal-register-correlations',
        suggestions,
      ),
    ).toBe(suggestions);
  });
});
