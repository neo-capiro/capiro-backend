/**
 * Phase 7 Workstream L — the Prisma adapter behind `OutboxDrainRepositoryV1`.
 *
 * The drain policy is pure and already tested. This is the part that touches a
 * database, and almost all of its weight is in one statement.
 *
 * ---------------------------------------------------------------------------
 * 1. The claim is a single statement, and that is the point
 * ---------------------------------------------------------------------------
 *
 * Selecting rows and then marking them `PROCESSING` in a second statement is
 * the obvious shape and it is wrong: two drainers can select the same row
 * before either marks it. `FOR UPDATE SKIP LOCKED` in a CTE feeding the UPDATE
 * closes that — a row locked by one drainer is invisible to the other, so
 * concurrent drainers partition the backlog instead of contending for it or
 * publishing the same change twice.
 *
 * The pause check rides inside the same statement as a `NOT EXISTS`. The policy
 * already checks `isDrainPaused` before claiming, and that check is the one
 * that reports `paused: true` to the caller; this second one closes the window
 * between those two round trips. A rollback pauses the drain precisely so a
 * batch cannot publish a snapshot's numbers after that snapshot stopped being
 * active, and "we checked a moment ago" is not that guarantee.
 *
 * ---------------------------------------------------------------------------
 * 2. The eligibility predicate is generated from the policy, not restated
 * ---------------------------------------------------------------------------
 *
 * The backoff schedule exists in TypeScript as `drainBackoffMsV1`. Writing the
 * same exponential curve again in SQL would create two schedules that agree
 * today and diverge the first time one is tuned, with no test able to see it.
 * `outboxBackoffCaseSqlV1` therefore *generates* the SQL `CASE` by calling the
 * policy function, and the database rehearsal seeds rows across the whole
 * attempt range and asserts the SQL claims exactly the set `isClaimableV1`
 * predicts.
 *
 * ---------------------------------------------------------------------------
 * 3. Money is resolved from the snapshots, not carried in the plan
 * ---------------------------------------------------------------------------
 *
 * Workstream E writes the outbox's before/after money columns as null. There
 * were two ways to fill them. Carrying the prior value forward in
 * `PromotionPlanItemV1` would change what `promotionPlanHashV1` hashes, which
 * invalidates every authorization already issued against an existing plan and
 * needs a deliberate schema-version bump — a large blast radius for a
 * reporting field. Reading it at drain time touches no hashed contract at all,
 * and reads it from the place it is already true: both snapshots are immutable,
 * so the answer is fixed and identical on every replay.
 *
 * So the claim resolves both sides by joining `defense_budget_canonical_row` on
 * (snapshot, entity, natural key) — the identity unique key — and `COALESCE`s
 * rather than overwrites, so a future writer that does populate the columns
 * wins over this fallback.
 *
 * Postgres pads a `NUMERIC(24,9)` to its declared scale on the way out, so
 * `1.25` returns as `1.250000000`, which is not canonical decimal form. Every
 * value read here goes through `parseCanonicalDecimalString`, exactly as
 * Workstream K's adapter does.
 */
import {
  drainBackoffMsV1,
  OUTBOX_BACKOFF_CAP_MS_V1,
  OUTBOX_MAX_ATTEMPTS_V1,
  OUTBOX_PROCESSING_LEASE_MS_V1,
  type OutboxDrainRepositoryV1,
  type OutboxRowV1,
  type PromotionRunSideEffectStatusV1,
} from './promotion-outbox-drain-v1.js';
import { isDrainPausedV1, type DrainPauseDelegateV1 } from './side-effect-drain-pause-prisma-v1.js';
import { parseCanonicalDecimalString } from '../contracts/decimal-string.js';

/** The Prisma surface this adapter needs, declared structurally so a test can fake it. */
export interface OutboxDrainPrismaLikeV1 {
  $queryRawUnsafe<T = unknown>(query: string, ...values: unknown[]): Promise<T>;
  defenseBudgetSideEffectDrainPause: DrainPauseDelegateV1;
}

export interface OutboxDrainRepositoryOptionsV1 {
  /** Overrides the policy lease. Present so the rehearsal can age a row without waiting. */
  processingLeaseMs?: number;
  maxAttempts?: number;
}

/** Longest error text kept on a row. Matches the legacy PE outbox's bound. */
const MAX_ERROR_LENGTH = 4_000;

/* ------------------------------------------------------------------ */
/* Generated SQL fragments                                             */
/* ------------------------------------------------------------------ */

/**
 * The backoff schedule as a SQL `CASE`, generated by calling the policy.
 *
 * Attempt counts beyond the retry ceiling fall to `ELSE`: such a row should
 * already be `POISON`, and if one is not, the capped delay is the safe answer.
 */
export function outboxBackoffCaseSqlV1(maxAttempts: number = OUTBOX_MAX_ATTEMPTS_V1): string {
  const arms: string[] = [];
  for (let attempts = 0; attempts <= maxAttempts; attempts += 1) {
    arms.push(`WHEN ${attempts} THEN ${drainBackoffMsV1(attempts)}`);
  }
  return `CASE o."attempts" ${arms.join(' ')} ELSE ${OUTBOX_BACKOFF_CAP_MS_V1} END`;
}

/**
 * The claim. See the header — one statement, locking, pause-aware, and it fills
 * the money columns from the two snapshots on its way past.
 */
export function outboxClaimSqlV1(options: OutboxDrainRepositoryOptionsV1 = {}): string {
  const leaseMs = options.processingLeaseMs ?? OUTBOX_PROCESSING_LEASE_MS_V1;
  const backoff = outboxBackoffCaseSqlV1(options.maxAttempts);
  return `
WITH eligible AS (
  SELECT o."id",
         o."old_snapshot_id",
         o."new_snapshot_id",
         o."canonical_entity",
         o."canonical_natural_key"
    FROM "defense_budget_promotion_outbox" o
    JOIN "defense_budget_promotion_activation" a ON a."id" = o."activation_id"
   WHERE a."domain" = $1
     AND a."environment" = $2
     AND NOT EXISTS (
           SELECT 1
             FROM "defense_budget_side_effect_drain_pause" p
            WHERE p."domain" = $1 AND p."environment" = $2 AND p."paused" = true)
     AND (
          (o."status" IN ('PENDING', 'FAILED')
           AND (o."attempts" = 0
                OR o."last_attempted_at" IS NULL
                OR o."last_attempted_at" <= $3::timestamptz - ((${backoff}) * INTERVAL '1 millisecond')))
          OR
          (o."status" = 'PROCESSING'
           AND o."last_attempted_at" IS NOT NULL
           AND o."last_attempted_at" <= $3::timestamptz - (${leaseMs} * INTERVAL '1 millisecond'))
         )
   ORDER BY o."created_at", o."id"
   LIMIT $4
   FOR UPDATE OF o SKIP LOCKED
)
UPDATE "defense_budget_promotion_outbox" t
   SET "status" = 'PROCESSING',
       "last_attempted_at" = $3::timestamptz,
       "old_original_value" = COALESCE(t."old_original_value", prior."money_original_value"),
       "old_value_millions"  = COALESCE(t."old_value_millions",  prior."money_value_millions"),
       "new_original_value" = COALESCE(t."new_original_value", curr."money_original_value"),
       "new_value_millions"  = COALESCE(t."new_value_millions",  curr."money_value_millions")
  FROM eligible e
  LEFT JOIN "defense_budget_canonical_row" prior
         ON prior."snapshot_id" = e."old_snapshot_id"
        AND prior."canonical_entity" = e."canonical_entity"
        AND prior."canonical_natural_key" = e."canonical_natural_key"
  LEFT JOIN "defense_budget_canonical_row" curr
         ON curr."snapshot_id" = e."new_snapshot_id"
        AND curr."canonical_entity" = e."canonical_entity"
        AND curr."canonical_natural_key" = e."canonical_natural_key"
 WHERE t."id" = e."id"
RETURNING t."id", t."dedupe_key", t."activation_id", t."old_snapshot_id", t."new_snapshot_id",
          t."canonical_entity", t."canonical_natural_key", t."family", t."fiscal_year",
          t."funding_field", t."stage",
          t."old_original_value", t."old_value_millions",
          t."new_original_value", t."new_value_millions",
          t."change_classification", t."suppress_alert", t."is_correction", t."is_rollback",
          t."attempts"`;
}

