/* The adapter                                                         */
/* ------------------------------------------------------------------ */

export function createOutboxDrainRepositoryPrismaV1(
  prisma: OutboxDrainPrismaLikeV1,
  options: OutboxDrainRepositoryOptionsV1 = {},
): OutboxDrainRepositoryV1 {
  const claimSql = outboxClaimSqlV1(options);

  return {
    async isDrainPaused(domain: string, environment: string) {
      return isDrainPausedV1(prisma.defenseBudgetSideEffectDrainPause, domain, environment);
    },

    async claimBatch(input) {
      const rows = await prisma.$queryRawUnsafe<Record<string, unknown>[]>(
        claimSql,
        input.domain,
        input.environment,
        input.now.toISOString(),
        input.limit,
      );
      return rows.map(outboxRowFromClaimV1);
    },

    async markDone(rowId: string, processedAt: Date) {
      /*
       * Guarded on PROCESSING. A row this drainer no longer owns — reclaimed
       * after a lease expiry, say — must not be marked done by the drainer that
       * lost it, or a genuinely unpublished row would read as delivered.
       */
      await prisma.$queryRawUnsafe(
        `UPDATE "defense_budget_promotion_outbox"
            SET "status" = 'DONE', "processed_at" = $2::timestamptz, "last_error" = NULL
          WHERE "id" = $1::uuid AND "status" = 'PROCESSING'
        RETURNING "id"`,
        rowId,
        processedAt.toISOString(),
      );
    },

    async markFailed(input) {
      await prisma.$queryRawUnsafe(
        `UPDATE "defense_budget_promotion_outbox"
            SET "status" = 'FAILED',
                "attempts" = "attempts" + 1,
                "last_error" = $2,
                "last_attempted_at" = $3::timestamptz
          WHERE "id" = $1::uuid AND "status" = 'PROCESSING'
        RETURNING "id"`,
        input.rowId,
        input.error.slice(0, MAX_ERROR_LENGTH),
        input.attemptedAt.toISOString(),
      );
    },

    async markPoison(input) {
      await prisma.$queryRawUnsafe(
        `UPDATE "defense_budget_promotion_outbox"
            SET "status" = 'POISON',
                "attempts" = "attempts" + 1,
                "last_error" = $2,
                "last_attempted_at" = $3::timestamptz
          WHERE "id" = $1::uuid AND "status" = 'PROCESSING'
        RETURNING "id"`,
        input.rowId,
        input.error.slice(0, MAX_ERROR_LENGTH),
        input.attemptedAt.toISOString(),
      );
    },

    async countsForActivation(activationId: string) {
      const rows = await prisma.$queryRawUnsafe<{ status: string; count: number }[]>(
        `SELECT "status", count(*)::int AS "count"
           FROM "defense_budget_promotion_outbox"
          WHERE "activation_id" = $1::uuid
          GROUP BY "status"`,
        activationId,
      );
      const by = new Map(rows.map((row) => [String(row.status), Number(row.count)]));
      return {
        pending: by.get('PENDING') ?? 0,
        processing: by.get('PROCESSING') ?? 0,
        failed: by.get('FAILED') ?? 0,
        poison: by.get('POISON') ?? 0,
      };
    },

    async setRunSideEffectStatus(input: {
      activationId: string;
      status: PromotionRunSideEffectStatusV1;
    }) {
      /*
       * The status filter is the guard. A run that failed pre-commit or was
       * cancelled never reaches the outbox, and a drain that touched an
       * unrelated activation must not be able to move such a run into
       * COMPLETED — which is the status an operator reads before believing the
       * side effects went out.
       */
      await prisma.$queryRawUnsafe(
        `UPDATE "defense_budget_promotion_run" r
            SET "status" = $2
           FROM "defense_budget_promotion_activation" a
          WHERE a."id" = $1::uuid
            AND r."id" = a."run_id"
            AND r."status" IN ('COMMITTED', 'SIDE_EFFECTS_PENDING', 'COMPLETED',
                               'COMMITTED_WITH_SIDE_EFFECT_FAILURE')
        RETURNING r."id"`,
        input.activationId,
        input.status,
      );
    },
  };
}
