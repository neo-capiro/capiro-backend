/* Row mapping                                                         */
/* ------------------------------------------------------------------ */

/**
 * A NUMERIC column into a canonical decimal string.
 *
 * A JavaScript `number` arriving here is refused rather than accepted. It would
 * mean the driver had already parsed an exact decimal through a float, and by
 * this point the precision is gone — accepting it would write a plausible wrong
 * number into a delta that a client can be alerted about. Failing loudly is the
 * only honest response, and the database rehearsal is what proves it never
 * happens in practice.
 */
export function exactDecimalFromColumnV1(value: unknown, column: string): string | null {
  if (value == null) return null;
  if (typeof value === 'number') {
    throw new Error(
      `${column} came back as a JavaScript number; exact decimal money must not pass through a float`,
    );
  }
  if (typeof value === 'string') return parseCanonicalDecimalString(value);
  if (
    typeof value === 'object' &&
    typeof (value as { toString?: unknown }).toString === 'function'
  ) {
    return parseCanonicalDecimalString((value as { toString(): string }).toString());
  }
  throw new Error(`${column} has an unreadable type: ${typeof value}`);
}

function text(value: unknown): string {
  return String(value);
}

function optionalText(value: unknown): string | null {
  return value == null ? null : String(value);
}

export function outboxRowFromClaimV1(row: Record<string, unknown>): OutboxRowV1 {
  return {
    id: text(row.id),
    dedupeKey: text(row.dedupe_key),
    activationId: text(row.activation_id),
    oldSnapshotId: optionalText(row.old_snapshot_id),
    newSnapshotId: text(row.new_snapshot_id),
    canonicalEntity: text(row.canonical_entity),
    canonicalNaturalKey: text(row.canonical_natural_key),
    family: text(row.family),
    fiscalYear: row.fiscal_year == null ? null : Number(row.fiscal_year),
    fundingField: optionalText(row.funding_field),
    stage: optionalText(row.stage),
    oldOriginalValue: optionalText(row.old_original_value),
    oldValueMillions: exactDecimalFromColumnV1(row.old_value_millions, 'old_value_millions'),
    newOriginalValue: optionalText(row.new_original_value),
    newValueMillions: exactDecimalFromColumnV1(row.new_value_millions, 'new_value_millions'),
    changeClassification: text(row.change_classification),
    suppressAlert: row.suppress_alert === true,
    isCorrection: row.is_correction === true,
    isRollback: row.is_rollback === true,
    attempts: Number(row.attempts ?? 0),
  };
}

