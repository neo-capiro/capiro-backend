import { Parser } from 'node-sql-parser';
import { PUBLIC_SQL_LIMITS, PUBLIC_SQL_RELATIONS, publicSqlRelation, type PublicSqlColumn } from './public-sql-registry.js';

export type PublicSqlErrorCode = 'INVALID_QUERY' | 'UNSUPPORTED_SQL' | 'UNKNOWN_RELATION' | 'UNKNOWN_FIELD' |
  'PARAMETER_MISMATCH' | 'SOURCE_UNAVAILABLE' | 'QUERY_TIMEOUT' | 'OUTPUT_LIMIT';
export class PublicSqlError extends Error {
  constructor(readonly code: PublicSqlErrorCode, message: string) { super(message); }
}
export type PublicSqlParameter = string | number | boolean | null;
export interface CompiledPublicSql {
  sql: string; params: PublicSqlParameter[]; columns: PublicSqlColumn[];
  relationsUsed: string[]; rowLimit: number; sqlLimit: number | null;
}
type Node = Record<string, unknown>;
type Origin = { relation: string; field: string };
type Field = PublicSqlColumn & { origin?: Origin; alias?: string };
type Scope = Map<string, Map<string, Field>>;
const dialect = { database: 'Postgresql' };
const parser = new Parser();
function fail(code: PublicSqlErrorCode, message: string): never { throw new PublicSqlError(code, message); }
function node(value: unknown): Node {
  if (!value || typeof value !== 'object' || Array.isArray(value)) fail('UNSUPPORTED_SQL', 'Unsupported SQL structure.');
  return value as Node;
}
function keys(value: Node, allowed: string[]): void {
  if (Object.keys(value).some((key) => !allowed.includes(key))) fail('UNSUPPORTED_SQL', 'Unsupported SQL clause or expression.');
}
function absent(...values: unknown[]): void {
  if (values.some((value) => value !== undefined && value !== null)) fail('UNSUPPORTED_SQL', 'Unsupported SQL clause or expression.');
}
function identifier(value: unknown): string {
  // Narrow identifiers are regenerated by the parser; never interpolate model text.
  if (typeof value !== 'string' || !/^[a-z_][a-z0-9_]{0,62}$/.test(value) || value.startsWith('__capiro') || ['__proto__', 'constructor', 'prototype'].includes(value))
    fail('UNSUPPORTED_SQL', 'Use lowercase SQL identifiers of at most 63 characters.');
  return value;
}
function named(value: unknown): string {
  const n = node(value); keys(n, ['type', 'value']);
  if (n.type !== 'default') fail('UNSUPPORTED_SQL', 'Quoted SQL identifiers are not supported.');
  return identifier(n.value);
}
function columnName(value: unknown): string {
  const n = node(value); keys(n, ['expr']); return named(n.expr);
}
function cleanColumn(field: Field): PublicSqlColumn {
  return { name: field.name, type: field.type, nullable: field.nullable, ...(field.unit ? { unit: field.unit } : {}) };
}
function canonicalTargets(origin: Origin): string[] {
  const relation = publicSqlRelation(origin.relation)!;
  const targets = [`${origin.relation}.${origin.field}`];
  for (const relationship of relation.relationships) {
    const i = relationship.fields.indexOf(origin.field);
    if (i >= 0) targets.push(`${relationship.referencedRelation}.${relationship.referencedFields[i]}`);
  }
  return targets;
}

/** A small, exhaustive PostgreSQL AST language. Unknown nodes/properties fail closed. */
class Compiler {
  readonly parameters = new Set<number>();
  readonly relations = new Set<string>();
  private nodes = 0;
  private cteCount = 0;
  private depth = 0;

  private boundCast(parameter: Node, field: Field): Node {
    const storageType = field.origin && publicSqlRelation(field.origin.relation)!.fields.find((f) => f.name === field.origin!.field)?.parameterType;
    const dataType = storageType ?? ({ string: 'TEXT', integer: 'BIGINT', decimal: 'NUMERIC', boolean: 'BOOLEAN', date: 'DATE', timestamp: 'TIMESTAMPTZ' } as const)[field.type];
    // PostgreSQL receives explicit Prisma parameter types. Cast only the bound node,
    // using server-owned types; values never become SQL text or JS numeric conversions.
    return { type: 'cast', keyword: 'cast', expr: parameter, symbol: 'as', target: [{ dataType, suffix: [] }] };
  }

  private column(value: unknown, scope: Scope, outputs?: Map<string, Field>): Field {
    const n = node(value); keys(n, ['type', 'table', 'column', 'collate']); absent(n.collate);
    if (n.type !== 'column_ref') fail('UNSUPPORTED_SQL', 'Expected a published column.');
    const name = columnName(n.column);
    if (n.table == null && outputs?.has(name)) return outputs.get(name)!;
    const candidates = n.table == null ? [...scope.values()].filter((fields) => fields.has(name)) :
      [scope.get(identifier(n.table))].filter((fields): fields is Map<string, Field> => !!fields && fields.has(name));
    if (candidates.length !== 1) fail('UNKNOWN_FIELD', 'Unknown or ambiguous published column.');
    const alias = n.table == null ? [...scope].find(([, fields]) => fields === candidates[0])![0] : identifier(n.table);
    return { ...candidates[0]!.get(name)!, alias };
  }

  private expression(value: unknown, scope: Scope, aggregate = false, outputs?: Map<string, Field>): Field {
    if (++this.nodes > 2048 || ++this.depth > 32) fail('UNSUPPORTED_SQL', 'SQL expression complexity exceeds the limit.');
    try {
      const n = node(value);
      switch (n.type) {
        case 'column_ref': return this.column(n, scope, outputs);
        case 'var': {
          keys(n, ['type', 'name', 'members', 'quoted', 'prefix']); absent(n.quoted);
          if (n.prefix !== '$' || !Array.isArray(n.members) || n.members.length || !Number.isInteger(n.name) || Number(n.name) < 1 || Number(n.name) > PUBLIC_SQL_LIMITS.maxParameters)
            fail('PARAMETER_MISMATCH', 'Use contiguous positional parameters $1 through $n.');
          this.parameters.add(Number(n.name));
          return { name: '', type: 'string', nullable: true };
        }
        case 'null': keys(n, ['type', 'value']); if (n.value !== null) fail('UNSUPPORTED_SQL', 'Invalid null.'); return { name: '', type: 'string', nullable: true };
        case 'bool': keys(n, ['type', 'value']); if (typeof n.value !== 'boolean') fail('UNSUPPORTED_SQL', 'Invalid boolean.'); return { name: '', type: 'boolean', nullable: false };
        case 'number': keys(n, ['type', 'value']); if (!Number.isSafeInteger(n.value)) fail('UNSUPPORTED_SQL', 'Bind exact numeric values as parameters.'); return { name: '', type: 'integer', nullable: false };
        case 'binary_expr': {
          keys(n, ['type', 'operator', 'left', 'right', 'parentheses']);
          if (n.parentheses !== undefined && typeof n.parentheses !== 'boolean') fail('UNSUPPORTED_SQL', 'Invalid parentheses.');
          if (!['=', '!=', '<>', '<', '<=', '>', '>=', 'AND', 'OR', 'IS', 'IS NOT', 'ILIKE', 'NOT ILIKE'].includes(String(n.operator)))
            fail('UNSUPPORTED_SQL', 'Unsupported SQL operator.');
          const l = this.expression(n.left, scope, aggregate, outputs), r = this.expression(n.right, scope, aggregate, outputs);
          if (node(n.left).type === 'var') n.left = this.boundCast(node(n.left), r);
          if (node(n.right).type === 'var') n.right = this.boundCast(node(n.right), l);
          if (['IS', 'IS NOT'].includes(String(n.operator)) && node(n.right).type !== 'null') fail('UNSUPPORTED_SQL', 'Only IS NULL and IS NOT NULL are supported.');
          if (['AND', 'OR'].includes(String(n.operator)) && (l.type !== 'boolean' || r.type !== 'boolean')) fail('UNSUPPORTED_SQL', 'Boolean predicates required.');
          return { name: '', type: 'boolean', nullable: l.nullable || r.nullable };
        }
        case 'aggr_func': {
          keys(n, ['type', 'name', 'args', 'over']); absent(n.over);
          if (!aggregate || !['COUNT', 'SUM', 'AVG', 'MIN', 'MAX'].includes(String(n.name))) fail('UNSUPPORTED_SQL', 'Unsupported aggregate.');
          const args = node(n.args); keys(args, ['expr', 'distinct', 'orderby', 'separator']); absent(args.orderby, args.separator);
          if (args.distinct != null && args.distinct !== 'DISTINCT') fail('UNSUPPORTED_SQL', 'Unsupported aggregate modifier.');
          const arg = node(args.expr);
          let field: Field;
          if (arg.type === 'star' && n.name === 'COUNT' && !args.distinct) {
            keys(arg, ['type', 'value']); if (arg.value !== '*') fail('UNSUPPORTED_SQL', 'Invalid star.');
            field = { name: '', type: 'integer', nullable: false };
          } else field = this.expression(arg, scope, false);
          if (['SUM', 'AVG'].includes(String(n.name)) && !['integer', 'decimal'].includes(field.type)) fail('UNSUPPORTED_SQL', 'SUM/AVG require numeric fields.');
          return { name: '', type: n.name === 'COUNT' ? 'integer' : n.name === 'AVG' ? 'decimal' : field.type,
            nullable: n.name !== 'COUNT', ...(field.unit && n.name !== 'COUNT' ? { unit: field.unit } : {}) };
        }
        default: return fail('UNSUPPORTED_SQL', 'Unsupported SQL expression; use published fields and bound scalar parameters.');
      }
    } finally { this.depth--; }
  }

  private join(value: unknown, scope: Scope, current: string): void {
    const pairs: [Field, Field][] = [];
    const visit = (value: unknown, depth: number): void => {
      if (depth > 16) fail('UNSUPPORTED_SQL', 'Join predicate exceeds the limit.');
      const n = node(value); keys(n, ['type', 'operator', 'left', 'right', 'parentheses']);
      if (n.type !== 'binary_expr') fail('UNSUPPORTED_SQL', 'Join on published keys with equality.');
      if (n.parentheses !== undefined && typeof n.parentheses !== 'boolean') fail('UNSUPPORTED_SQL', 'Invalid parentheses.');
      if (n.operator === 'AND') { visit(n.left, depth + 1); visit(n.right, depth + 1); return; }
      if (n.operator !== '=') fail('UNSUPPORTED_SQL', 'Join on published keys with equality.');
      const l = this.column(n.left, scope), r = this.column(n.right, scope);
      if (!l.origin || !r.origin || l.alias === r.alias || (l.alias !== current && r.alias !== current) ||
        !canonicalTargets(l.origin).some((target) => canonicalTargets(r.origin!).includes(target)))
        fail('UNSUPPORTED_SQL', 'Join fields must share a published canonical key.');
      // Same-name descriptive columns are not keys, even within a self join.
      const keyField = (f: Field): boolean => {
        const relation = publicSqlRelation(f.origin!.relation)!;
        return relation.primaryKey.includes(f.origin!.field) || relation.relationships.some((r) => r.fields.includes(f.origin!.field));
      };
      if (!keyField(l) || !keyField(r)) fail('UNSUPPORTED_SQL', 'Join fields must be canonical keys.');
      pairs.push([l, r]);
    };
    visit(value, 0);
    for (const [l, r] of pairs) if (l.origin!.field === 'project_code' || r.origin!.field === 'project_code') {
      if (!pairs.some(([a, b]) => a.origin!.field === 'pe_code' && b.origin!.field === 'pe_code' &&
        ((a.alias === l.alias && b.alias === r.alias) || (a.alias === r.alias && b.alias === l.alias))))
        fail('UNSUPPORTED_SQL', 'Project identity also requires pe_code.');
    }
  }

  select(value: unknown, inherited = new Map<string, Map<string, Field>>(), level = 0): { fields: Map<string, Field>; limit: number | null } {
    if (level > 8) fail('UNSUPPORTED_SQL', 'CTE depth exceeds the limit.');
    const n = node(value);
    keys(n, ['with', 'type', 'options', 'distinct', 'columns', 'into', 'from', 'where', 'groupby', 'having', 'orderby', 'limit', 'window']);
    if (n.type !== 'select') fail('UNSUPPORTED_SQL', 'Only SELECT is supported.');
    absent(n.options, n.window);
    const into = node(n.into); keys(into, ['position']); absent(into.position);
    const distinct = node(n.distinct); keys(distinct, ['type']);
    if (distinct.type !== null && distinct.type !== 'DISTINCT') fail('UNSUPPORTED_SQL', 'Unsupported DISTINCT clause.');
    const ctes = new Map(inherited);
    if (n.with != null) {
      if (!Array.isArray(n.with)) fail('UNSUPPORTED_SQL', 'Unsupported WITH clause.');
      for (const value of n.with) {
        if (++this.cteCount > 8) fail('UNSUPPORTED_SQL', 'Too many CTEs.');
        const cte = node(value); keys(cte, ['name', 'stmt', 'columns']); absent(cte.columns);
        const name = named(cte.name);
        if (ctes.has(name) || publicSqlRelation(name)) fail('UNSUPPORTED_SQL', 'CTEs cannot shadow published relations or other CTEs.');
        ctes.set(name, this.select(cte.stmt, ctes, level + 1).fields);
      }
    }
    if (!Array.isArray(n.from) || n.from.length < 1 || n.from.length > 8) fail('UNSUPPORTED_SQL', 'Select from one to eight published relations or CTEs.');
    const scope: Scope = new Map();
    for (let i = 0; i < n.from.length; i++) {
      const from = node(n.from[i]); keys(from, ['db', 'table', 'as', 'join', 'on']); absent(from.db);
      const table = identifier(from.table), alias = from.as == null ? table : identifier(from.as);
      if (scope.has(alias)) fail('UNSUPPORTED_SQL', 'Duplicate relation alias.');
      let fields = ctes.get(table);
      if (!fields) {
        const relation = publicSqlRelation(table);
        if (!relation) fail('UNKNOWN_RELATION', 'Use a relation published by describe_capiro_data.');
        this.relations.add(table);
        fields = new Map(relation.fields.map((field) => [field.name, { ...cleanColumn(field), origin: { relation: table, field: field.name } }]));
      }
      if (i === 0) absent(from.join, from.on);
      else if (!['INNER JOIN', 'LEFT JOIN'].includes(String(from.join))) fail('UNSUPPORTED_SQL', 'Use explicit INNER or LEFT JOIN on published keys.');
      scope.set(alias, new Map([...fields].map(([name, field]) => [name, { ...field, nullable: field.nullable || from.join === 'LEFT JOIN' }])));
      if (i > 0) this.join(from.on, scope, alias);
    }
    if (n.where != null && this.expression(n.where, scope).type !== 'boolean') fail('UNSUPPORTED_SQL', 'WHERE requires a predicate.');
    if (n.groupby != null) {
      const group = node(n.groupby); keys(group, ['columns']);
      if (!Array.isArray(group.columns) || group.columns.length > PUBLIC_SQL_LIMITS.maxColumns) fail('UNSUPPORTED_SQL', 'Invalid GROUP BY.');
      for (const column of group.columns) this.column(column, scope);
    }
    if (!Array.isArray(n.columns) || !n.columns.length || n.columns.length > PUBLIC_SQL_LIMITS.maxColumns) fail('UNSUPPORTED_SQL', 'Select at most 32 named columns.');
    const output = new Map<string, Field>();
    for (const value of n.columns) {
      const column = node(value); keys(column, ['type', 'expr', 'as']);
      if (column.type !== 'expr') fail('UNSUPPORTED_SQL', 'Unsupported projection.');
      const expr = node(column.expr);
      if (!['column_ref', 'aggr_func'].includes(String(expr.type))) fail('UNSUPPORTED_SQL', 'Select published fields or named aggregates.');
      const field = this.expression(expr, scope, true);
      const name = column.as == null ? (expr.type === 'column_ref' ? columnName(expr.column) : fail('UNSUPPORTED_SQL', 'Name each aggregate with AS.')) : identifier(column.as);
      if (output.has(name)) fail('UNSUPPORTED_SQL', 'Output names must be unique.');
      output.set(name, { ...field, name, alias: undefined });
    }
    if (n.having != null && this.expression(n.having, scope, true).type !== 'boolean') fail('UNSUPPORTED_SQL', 'HAVING requires a predicate.');
    if (n.orderby != null) {
      if (!Array.isArray(n.orderby) || n.orderby.length > PUBLIC_SQL_LIMITS.maxColumns) fail('UNSUPPORTED_SQL', 'Invalid ORDER BY.');
      for (const value of n.orderby) {
        const order = node(value); keys(order, ['expr', 'type', 'nulls']); absent(order.nulls);
        if (order.type != null && !['ASC', 'DESC'].includes(String(order.type))) fail('UNSUPPORTED_SQL', 'Invalid ordering.');
        this.column(order.expr, scope, output);
      }
    }
    const limit = node(n.limit); keys(limit, ['seperator', 'value']);
    if (limit.seperator !== '' || !Array.isArray(limit.value) || limit.value.length > 1) fail('UNSUPPORTED_SQL', 'OFFSET and alternate LIMIT forms are not supported.');
    let sqlLimit: number | null = null;
    if (limit.value.length) {
      if (level !== 0) fail('UNSUPPORTED_SQL', 'Apply LIMIT only to the final SELECT so coverage reports it explicitly.');
      const value = node(limit.value[0]); keys(value, ['type', 'value']);
      if (value.type !== 'number' || !Number.isInteger(value.value) || Number(value.value) < 0 || Number(value.value) > PUBLIC_SQL_LIMITS.maxRowLimit)
        fail('UNSUPPORTED_SQL', 'SQL LIMIT must be an integer from 0 to 1000.');
      sqlLimit = Number(value.value);
    }
    return { fields: output, limit: sqlLimit };
  }
}

export function compilePublicSql(input: unknown): CompiledPublicSql {
  const request = node(input); keys(request, ['sql', 'parameters', 'rowLimit']);
  if (typeof request.sql !== 'string' || !request.sql.trim() || Buffer.byteLength(request.sql, 'utf8') > PUBLIC_SQL_LIMITS.maxSqlBytes)
    fail('INVALID_QUERY', 'SQL must contain 1 to 16384 UTF-8 bytes.');
  if (!Array.isArray(request.parameters) || request.parameters.length > PUBLIC_SQL_LIMITS.maxParameters ||
    request.parameters.some((p) => p !== null && typeof p !== 'string' && typeof p !== 'boolean' &&
      !(typeof p === 'number' && Number.isFinite(p) && Math.abs(p) <= Number.MAX_SAFE_INTEGER)) ||
    Buffer.byteLength(JSON.stringify(request.parameters), 'utf8') > PUBLIC_SQL_LIMITS.maxParameterBytes)
    fail('PARAMETER_MISMATCH', 'Bind at most 64 scalar parameters within 32768 UTF-8 bytes; use strings for exact decimal/int64 values.');
  const rowLimit = request.rowLimit ?? PUBLIC_SQL_LIMITS.defaultRowLimit;
  if (!Number.isInteger(rowLimit) || Number(rowLimit) < 1 || Number(rowLimit) > PUBLIC_SQL_LIMITS.maxRowLimit) fail('INVALID_QUERY', 'rowLimit must be an integer from 1 to 1000.');
  let ast: unknown;
  try { ast = parser.astify(request.sql, dialect); } catch { return fail('UNSUPPORTED_SQL', 'SQL is outside the supported PostgreSQL SELECT subset.'); }
  if (Array.isArray(ast)) {
    if (ast.length !== 1) fail('UNSUPPORTED_SQL', 'Exactly one SELECT is required.');
    ast = ast[0];
  }
  const compiler = new Compiler(), selected = compiler.select(ast);
  if (compiler.parameters.size !== request.parameters.length || request.parameters.some((_, i) => !compiler.parameters.has(i + 1)))
    fail('PARAMETER_MISMATCH', 'Every supplied parameter must be referenced, consecutively from $1.');
  const relationsUsed = PUBLIC_SQL_RELATIONS.filter((relation) => compiler.relations.has(relation.name)).map((relation) => relation.name);
  const projections = relationsUsed.map((name) => {
    const relation = publicSqlRelation(name)!;
    return `${name} AS (SELECT ${relation.fields.map((f) => `"${f.name}"`).join(', ')} FROM public."${relation.table}"${relation.predicate ? ` WHERE ${relation.predicate}` : ''})`;
  });
  // These AST nodes come only from reviewed registry projections, never caller fragments.
  const trusted = node(parser.astify(`WITH ${projections.join(', ')} SELECT 1`, dialect));
  const statement = node(ast);
  statement.with = [...trusted.with as unknown[], ...(statement.with as unknown[] | null ?? [])];
  let sql: string;
  try { sql = parser.sqlify(statement as never, dialect); } catch { return fail('UNSUPPORTED_SQL', 'Cannot regenerate supported PostgreSQL SELECT.'); }
  const columns = [...selected.fields.values()].map(cleanColumn);
  // PostgreSQL casts exact numeric output to text before Prisma can convert it.
  const projection = columns.map((column) => `"${column.name}"${['integer', 'decimal'].includes(column.type) ? '::text' : ''} AS "${column.name}"`).join(', ');
  return { sql: `SELECT ${projection} FROM (${sql}) AS "__capiro_result" LIMIT ${Number(rowLimit) + 1}`,
    params: [...request.parameters] as PublicSqlParameter[], columns, relationsUsed, rowLimit: Number(rowLimit), sqlLimit: selected.limit };
}
