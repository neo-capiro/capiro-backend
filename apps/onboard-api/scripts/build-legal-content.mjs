// Generates src/legal/legal-doc-content.ts from the counsel-provided source
// text in src/legal/assets/*.txt. Deterministic line-based converter: each
// non-empty source line is one block (the source wraps paragraphs to a single
// line), blank lines separate blocks, "- " lines become <ul><li>, and the
// first line plus SECTION/EXHIBIT/"N. HEADING" lines become headings.
//
//   node scripts/build-legal-content.mjs
//
// Re-run after editing the source .txt, then bump LEGAL_SEED_VERSION in
// legal-doc-seed.ts (versions are immutable SOC-2 consent evidence — never
// change a shipped version's text in place).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assets = resolve(here, '..', 'src', 'legal', 'assets');

function esc(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function isHeading(t) {
  return (
    /^SECTION \d+:/.test(t) || /^EXHIBIT [A-Z]:/.test(t) || /^\d+\.\s+[A-Z]/.test(t)
  );
}

function toHtml(text) {
  const lines = text.split(/\r?\n/);
  const out = [];
  let inList = false;
  let seenTitle = false;
  const closeList = () => {
    if (inList) {
      out.push('</ul>');
      inList = false;
    }
  };
  for (const raw of lines) {
    const t = raw.trim();
    if (t === '') continue;
    if (t === '---') {
      closeList();
      out.push('<hr class="doc-rule"/>');
      continue;
    }
    if (t.startsWith('- ')) {
      if (!inList) {
        out.push('<ul>');
        inList = true;
      }
      out.push(`<li>${esc(t.slice(2))}</li>`);
      continue;
    }
    closeList();
    if (!seenTitle) {
      out.push(`<h2 class="doc-title">${esc(t)}</h2>`);
      seenTitle = true;
      continue;
    }
    if (isHeading(t)) {
      out.push(`<h3>${esc(t)}</h3>`);
      continue;
    }
    out.push(`<p>${esc(t)}</p>`);
  }
  closeList();
  return out.join('\n');
}

const tos = toHtml(readFileSync(resolve(assets, 'terms-of-service.txt'), 'utf8'));
const sa = toHtml(readFileSync(resolve(assets, 'subscription-agreement.txt'), 'utf8'));

const banner =
  '// AUTO-GENERATED by scripts/build-legal-content.mjs from the counsel-provided\n' +
  '// source text in src/legal/assets/*.txt. DO NOT EDIT BY HAND — edit the source\n' +
  '// .txt and re-run the generator, then bump LEGAL_SEED_VERSION in\n' +
  '// legal-doc-seed.ts (shipped versions are immutable SOC-2 consent evidence).\n' +
  '/* eslint-disable */\n';

const body =
  `${banner}\n` +
  `export const TERMS_OF_SERVICE_HTML = ${JSON.stringify(tos)};\n\n` +
  `export const SUBSCRIPTION_AGREEMENT_HTML = ${JSON.stringify(sa)};\n`;

writeFileSync(resolve(here, '..', 'src', 'legal', 'legal-doc-content.ts'), body, 'utf8');
// eslint-disable-next-line no-console
console.log(
  `wrote legal-doc-content.ts — ToS ${tos.length} chars, SA ${sa.length} chars`,
);
