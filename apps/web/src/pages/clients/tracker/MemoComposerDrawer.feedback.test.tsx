import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { beforeEach, describe, expect, test, vi } from 'vitest';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { App as AntApp } from 'antd';
import { MemoryRouter } from 'react-router-dom';
import { MemoComposerDrawer, textDiffRatio, MEMO_HEAVY_EDIT_THRESHOLD } from './MemoComposerDrawer.js';
import type { FeedItem } from './intel-feed-api.js';
import type { AlertMemoResult } from './alert-actions-api.js';

/**
 * §4.10 (Gate E phase f, f-5/f-7 case 8) — the composer emits `memo_generated`
 * on a successful draft, and `memo_heavily_edited` on save ONLY when the saved
 * text differs from what was generated by more than MEMO_HEAVY_EDIT_THRESHOLD
 * — a real computed ratio (edge case 16: `dirty` alone is true after one
 * keystroke, so it cannot gate this by itself).
 */

const apiGetMock = vi.fn();
const apiPatchMock = vi.fn();
const apiPostMock = vi.fn();

vi.mock('../../../lib/use-api.js', () => ({
  useApi: () => ({ get: apiGetMock, patch: apiPatchMock, post: apiPostMock }),
}));

function setupBrowserMocks() {
  Object.defineProperty(window, 'matchMedia', {
    writable: true,
    value: vi.fn().mockImplementation((query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: vi.fn(),
      removeListener: vi.fn(),
      addEventListener: vi.fn(),
      removeEventListener: vi.fn(),
      dispatchEvent: vi.fn(),
    })),
  });
  class ResizeObserverMock {
    observe() {}
    unobserve() {}
    disconnect() {}
  }
  vi.stubGlobal('ResizeObserver', ResizeObserverMock);
  if (!HTMLElement.prototype.scrollIntoView) {
    HTMLElement.prototype.scrollIntoView = vi.fn();
  }
}

function makeItem(overrides: Partial<FeedItem> = {}): FeedItem {
  return {
    id: 'alert-1',
    clientId: 'client-1',
    sourceType: 'bill',
    kind: 'bill_update',
    severity: 'critical',
    materiality: 'high',
    score: 80,
    clientImpact: null,
    urgency: null,
    title: 'H.R. 8800: Rule granted',
    whyItMatters: 'Directly affects the client.',
    recommendedAction: null,
    evidence: {},
    status: 'new',
    createdAt: '2026-07-01T00:00:00.000Z',
    ...overrides,
  } as FeedItem;
}

const GENERATED_MARKDOWN = '# Client memo\n\nBody text.';

function baseMemoResult(overrides: Partial<AlertMemoResult> = {}): AlertMemoResult {
  return {
    title: 'Client memo — H.R. 8800',
    markdown: GENERATED_MARKDOWN,
    sections: [],
    sources: [],
    document: { attachmentId: 'att-1', fileName: 'memo.docx' },
    usedTenantKey: false,
    model: 'claude-sonnet-5',
    lowConfidence: false,
    memoryFilesUsed: [],
    held: false,
    reviewRequestId: null,
    heldReason: '',
    ...overrides,
  };
}

function renderDrawer(item: FeedItem = makeItem()) {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
  return render(
    <QueryClientProvider client={queryClient}>
      <AntApp>
        <MemoryRouter initialEntries={['/clients']}>
          <MemoComposerDrawer open={true} onClose={() => {}} clientId="client-1" clientName="Acme Corp" item={item} />
        </MemoryRouter>
      </AntApp>
    </QueryClientProvider>,
  );
}

/** Records every `/tracker/feedback` POST body so a signal's presence/absence is assertable. */
function wireApi() {
  const calls = { generate: 0, save: 0, link: 0, feedback: [] as Array<{ signal: string }> };
  apiPostMock.mockImplementation(async (url: string, body?: unknown) => {
    if (url.endsWith('/memo-link')) {
      calls.link += 1;
      return { data: {} };
    }
    if (url.endsWith('/alert-memo/save')) {
      calls.save += 1;
      return { data: { document: { attachmentId: 'att-2', fileName: 'memo.docx' }, title: 'Client memo — H.R. 8800' } };
    }
    if (url.endsWith('/alert-memo')) {
      calls.generate += 1;
      return { data: baseMemoResult() };
    }
    if (url.includes('/tracker/feedback')) {
      calls.feedback.push(body as { signal: string });
      return { data: { ok: true } };
    }
    return { data: {} };
  });
  return calls;
}

describe('MemoComposerDrawer — §4.10 feedback signals (f-5/f-7 case 8)', () => {
  beforeEach(() => {
    apiGetMock.mockReset();
    apiPatchMock.mockReset();
    apiPostMock.mockReset();
    setupBrowserMocks();
  });

  test('generating a memo emits memo_generated', async () => {
    const calls = wireApi();
    renderDrawer();
    await waitFor(() => expect(calls.generate).toBe(1));
    await waitFor(() => expect(calls.feedback.some((f) => f.signal === 'memo_generated')).toBe(true));
  });

  test('saving WITHOUT editing does not emit memo_heavily_edited', async () => {
    const calls = wireApi();
    renderDrawer();
    await waitFor(() => expect(screen.getByText(/Memo drafted and filed in Documents/i)).toBeTruthy());
    calls.feedback.length = 0; // clear the memo_generated signal already recorded above

    fireEvent.click(screen.getByRole('button', { name: /Save to Documents/i }));

    await waitFor(() => expect(calls.save).toBe(1));
    expect(calls.feedback.some((f) => f.signal === 'memo_heavily_edited')).toBe(false);
  });

  test('saving a HEAVILY edited memo emits memo_heavily_edited', async () => {
    const calls = wireApi();
    renderDrawer();
    await waitFor(() => expect(screen.getByText(/Memo drafted and filed in Documents/i)).toBeTruthy());
    calls.feedback.length = 0;

    const rewritten =
      'Completely different memo content that shares almost nothing with the original draft text, rewritten from scratch by the analyst.';
    expect(textDiffRatio(GENERATED_MARKDOWN, rewritten)).toBeGreaterThan(MEMO_HEAVY_EDIT_THRESHOLD);
    fireEvent.change(screen.getByRole('textbox'), { target: { value: rewritten } });

    fireEvent.click(screen.getByRole('button', { name: /Save to Documents/i }));

    await waitFor(() => expect(calls.save).toBe(1));
    await waitFor(() => expect(calls.feedback.some((f) => f.signal === 'memo_heavily_edited')).toBe(true));
  });

  test('a small edit (below the 20% threshold) does not emit memo_heavily_edited', async () => {
    const calls = wireApi();
    renderDrawer();
    await waitFor(() => expect(screen.getByText(/Memo drafted and filed in Documents/i)).toBeTruthy());
    calls.feedback.length = 0;

    const tweaked = `${GENERATED_MARKDOWN} A.`; // a couple of characters appended
    expect(textDiffRatio(GENERATED_MARKDOWN, tweaked)).toBeLessThan(MEMO_HEAVY_EDIT_THRESHOLD);
    fireEvent.change(screen.getByRole('textbox'), { target: { value: tweaked } });

    fireEvent.click(screen.getByRole('button', { name: /Save to Documents/i }));

    await waitFor(() => expect(calls.save).toBe(1));
    expect(calls.feedback.some((f) => f.signal === 'memo_heavily_edited')).toBe(false);
  });
});
