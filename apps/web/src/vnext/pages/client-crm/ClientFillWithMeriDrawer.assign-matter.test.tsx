import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { describe, expect, it, vi, beforeEach } from 'vitest';
import { ClientFillWithMeriDrawer } from './ClientFillWithMeriDrawer.js';

/**
 * §22/23 follow-up: "Attach to Matter X" / "Create new Matter" directly on
 * a still-pending advocacy finding, IS the review/approval decision and
 * commits immediately — no staging queue, no "Save for later" state, no
 * second application workflow (see Attach-to-Matter/Create-Matter product
 * decision recorded in docs/handoff/advocacy-history-final-closeout.md).
 *
 * Drives the REAL useClientFillWithMeri hook (not a stub) with only
 * useApi mocked, matching AdvocacyMattersTab.test.tsx's convention — the
 * hook's phase/proposals derivation is exactly what this UI depends on,
 * so stubbing it out would test nothing real about the wiring.
 */

const getMock = vi.hoisted(() => vi.fn());
const postMock = vi.hoisted(() => vi.fn());
vi.mock('../../../lib/use-api.js', () => ({
  useApi: () => ({ get: getMock, post: postMock }),
}));

const clientId = 'client-1';

const pendingAdvocacyFinding = (overrides: Partial<Record<string, unknown>> = {}) => ({
  id: 'finding-1',
  runId: 'run-1',
  kind: 'advocacy_record',
  targetKey: 'advocacy_record',
  source: 'lda',
  factKind: 'fact',
  currentValue: null,
  proposedValue: {
    externalKey: 'lda:2027-q1-1234',
    title: 'FY27 autonomous systems funding request',
    recordType: 'federal_lobbying',
    sourceType: 'lda',
  },
  evidence: [],
  confidence: 0.9,
  status: 'pending',
  appliedAt: null,
  createdAt: '2027-01-15T00:00:00.000Z',
  ...overrides,
});

const fillRunFixture = (overrides: Partial<Record<string, unknown>> = {}) => ({
  id: 'run-1',
  clientId,
  status: 'completed',
  requestedSources: ['lda'],
  sourceStates: {},
  summary: {},
  error: null,
  startedAt: '2027-01-15T00:00:00.000Z',
  completedAt: '2027-01-15T00:05:00.000Z',
  findings: [pendingAdvocacyFinding()],
  ...overrides,
});

const matterFixture = (overrides: Partial<Record<string, unknown>> = {}) => ({
  id: 'matter-1',
  title: 'FY27 Ground Robotics Funding',
  matterType: 'program_element',
  status: 'active',
  summary: null,
  primaryPeCode: '0605053A',
  primaryBillId: null,
  externalKey: 'pe:0605053A',
  autoGenerated: false,
  openedAt: '2026-06-01T00:00:00.000Z',
  lastActivityAt: '2026-08-01T00:00:00.000Z',
  recordCount: 1,
  outcomeCount: 0,
  linkCount: 0,
  createdAt: '2026-06-01T00:00:00.000Z',
  updatedAt: '2026-08-01T00:00:00.000Z',
  ...overrides,
});

function renderDrawer(onOpenMatter?: (matterId: string) => void) {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  return render(
    <QueryClientProvider client={queryClient}>
      <ClientFillWithMeriDrawer
        clientId={clientId}
        clientName="Overland AI"
        open
        onClose={() => {}}
        onOpenMatter={onOpenMatter}
      />
    </QueryClientProvider>,
  );
}

beforeEach(() => {
  getMock.mockReset();
  postMock.mockReset();
  getMock.mockImplementation(async (url: string) => {
    if (url.endsWith('/latest')) return { data: fillRunFixture() };
    if (url.endsWith('/advocacy-matters')) return { data: [matterFixture()] };
    return { data: fillRunFixture() };
  });
});

describe('ClientFillWithMeriDrawer — Attach to Matter / Create new Matter on a pending finding (§22/23 follow-up)', () => {
  it('attaches a pending finding to an existing Matter, applying it immediately', async () => {
    postMock.mockResolvedValue({ data: { findingId: 'finding-1', matterId: 'matter-1', alreadyApplied: false } });
    renderDrawer();

    await waitFor(() => expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0));
    fireEvent.click(screen.getByText('Attach to Matter'));

    await waitFor(() => expect(screen.getByText('Attach to a Matter')).toBeInTheDocument());
    const dialogs = screen.getAllByRole('dialog');
    const modal = dialogs[dialogs.length - 1]!;
    fireEvent.change(await within(modal).findByRole('combobox'), { target: { value: 'matter-1' } });
    fireEvent.click(within(modal).getByRole('button', { name: 'Attach now' }));

    await waitFor(() =>
      expect(postMock).toHaveBeenCalledWith(
        '/api/clients/client-1/fill-with-meri/runs/run-1/findings/finding-1/assign-matter',
        { matterId: 'matter-1' },
      ),
    );
  });

  it('creates a new Matter from a pending finding, applying the record into it immediately', async () => {
    postMock.mockResolvedValue({ data: { findingId: 'finding-1', matterId: 'matter-new', alreadyApplied: false } });
    renderDrawer();

    await waitFor(() => expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0));
    fireEvent.click(screen.getByText('Attach to Matter'));

    await waitFor(() => expect(screen.getByText('Attach to a Matter')).toBeInTheDocument());
    const dialogs = screen.getAllByRole('dialog');
    const modal = dialogs[dialogs.length - 1]!;
    fireEvent.click(within(modal).getByLabelText('Create new'));
    fireEvent.change(within(modal).getByLabelText('Matter title'), {
      target: { value: 'FY27 autonomous systems funding request' },
    });
    fireEvent.click(within(modal).getByRole('button', { name: 'Create and apply' }));

    await waitFor(() =>
      expect(postMock).toHaveBeenCalledWith(
        '/api/clients/client-1/fill-with-meri/runs/run-1/findings/finding-1/assign-matter',
        { newMatter: { title: 'FY27 autonomous systems funding request' } },
      ),
    );
  });

  it('opens the newly created/attached Matter via onOpenMatter once the server confirms', async () => {
    postMock.mockResolvedValue({ data: { findingId: 'finding-1', matterId: 'matter-new', alreadyApplied: false } });
    const onOpenMatter = vi.fn();
    renderDrawer(onOpenMatter);

    await waitFor(() => expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0));
    fireEvent.click(screen.getByText('Attach to Matter'));
    await waitFor(() => expect(screen.getByText('Attach to a Matter')).toBeInTheDocument());
    const modal = screen.getAllByRole('dialog').at(-1)!;
    fireEvent.change(await within(modal).findByRole('combobox'), { target: { value: 'matter-1' } });
    fireEvent.click(within(modal).getByRole('button', { name: 'Attach now' }));

    await waitFor(() => expect(onOpenMatter).toHaveBeenCalledWith('matter-new'));
  });

  it('shows a short "Applying…" state instead of optimistically clearing the finding before the server confirms', async () => {
    let resolvePost: (value: { data: { findingId: string; matterId: string; alreadyApplied: boolean } }) => void;
    postMock.mockImplementation(
      () =>
        new Promise((resolve) => {
          resolvePost = resolve;
        }),
    );
    renderDrawer();

    await waitFor(() => expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0));
    fireEvent.click(screen.getByText('Attach to Matter'));
    await waitFor(() => expect(screen.getByText('Attach to a Matter')).toBeInTheDocument());
    const modal = screen.getAllByRole('dialog').at(-1)!;
    fireEvent.change(await within(modal).findByRole('combobox'), { target: { value: 'matter-1' } });
    fireEvent.click(within(modal).getByRole('button', { name: 'Attach now' }));

    // The modal's own submit button is the "Applying…" indicator — no
    // separate optimistic UI, per the non-optimistic requirement.
    await waitFor(() => expect(within(modal).getByRole('button', { name: 'Applying…' })).toBeInTheDocument());
    // Still pending in the underlying data — not removed/faded out ahead
    // of the server's real answer (non-optimistic per the requirement:
    // "show a short applying state and update after the server confirms").
    expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0);

    resolvePost!({ data: { findingId: 'finding-1', matterId: 'matter-1', alreadyApplied: false } });
    await waitFor(() => expect(screen.queryByText('Attach to a Matter')).not.toBeInTheDocument());
  });

  it('shows an error and leaves the finding visible/pending when the server call fails — no partial UI state', async () => {
    postMock.mockRejectedValue({ response: { data: { message: 'Target advocacy matter not found' } } });
    renderDrawer();

    await waitFor(() => expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0));
    fireEvent.click(screen.getByText('Attach to Matter'));
    await waitFor(() => expect(screen.getByText('Attach to a Matter')).toBeInTheDocument());
    const modal = screen.getAllByRole('dialog').at(-1)!;
    fireEvent.change(await within(modal).findByRole('combobox'), { target: { value: 'matter-1' } });
    fireEvent.click(within(modal).getByRole('button', { name: 'Attach now' }));

    await waitFor(() => expect(within(modal).getByText('Target advocacy matter not found')).toBeInTheDocument());
    // The finding is still on screen, still actionable — nothing was
    // silently removed or marked applied on a failed request.
    expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0);
    expect(screen.getByText('Attach to Matter')).toBeInTheDocument();
  });

  it('keeps "Not advocacy" wired to the existing immediate-reject path, unaffected by the new assign-matter action', async () => {
    postMock.mockResolvedValue({ data: {} });
    renderDrawer();

    await waitFor(() => expect(screen.getAllByText('FY27 autonomous systems funding request').length).toBeGreaterThan(0));
    fireEvent.click(screen.getByText('Not advocacy'));

    await waitFor(() =>
      expect(postMock).toHaveBeenCalledWith('/api/clients/client-1/fill-with-meri/findings/finding-1/reject', {
        reason: 'Not advocacy (reviewed in Fill with Meri)',
      }),
    );
  });

  it('does not offer "Attach to Matter" for an advocacy_outcome finding — only advocacy_record findings get direct Matter assignment', async () => {
    getMock.mockImplementation(async (url: string) => {
      if (!url.endsWith('/advocacy-matters')) {
        return {
          data: fillRunFixture({
            findings: [
              pendingAdvocacyFinding({
                id: 'finding-outcome-1',
                kind: 'advocacy_outcome',
                proposedValue: { title: 'HAC-D marked up +$18M', kind: 'funding_changed' },
              }),
            ],
          }),
        };
      }
      if (url.endsWith('/advocacy-matters')) return { data: [matterFixture()] };
      return { data: fillRunFixture() };
    });
    renderDrawer();

    await waitFor(() => expect(screen.getAllByText('HAC-D marked up +$18M').length).toBeGreaterThan(0));
    expect(screen.queryByText('Attach to Matter')).not.toBeInTheDocument();
    // "Not advocacy" is still offered — only the Matter-assign action is
    // record-specific.
    expect(screen.getByText('Not advocacy')).toBeInTheDocument();
  });
});
