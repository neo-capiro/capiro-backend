export function ClientCrmAdvocacyMattersProto({
  client,
  initialOpenMatterId,
  onOpenMatterConsumed,
}: {
  client: Client;
  /** §22/23 follow-up: when a reviewer creates/attaches a Matter directly
   *  from the Fill-with-Meri drawer, ClientCrmPage navigates here and
   *  seeds this so the Matter opens immediately instead of landing on the
   *  bare list. Read once via useState's lazy initializer — a later
   *  navigation to this same tab without a fresh matter id must NOT
   *  re-open a stale one, so this is intentionally not synced with a
   *  useEffect that re-runs on every `initialOpenMatterId` change. */
  initialOpenMatterId?: string | null;
  /** Called once, after mount, if `initialOpenMatterId` was non-null — lets
   *  the parent clear its one-shot handoff state so switching away and
   *  back to this same view does not attempt to reopen a stale Matter.
   *  Deliberately NOT called from the parent's render body (that would be
   *  a cross-component state update during render); this component calls
   *  it itself, from an effect, which is the correct place to react to
   *  "this prop was consumed". */
  onOpenMatterConsumed?: () => void;
}) {
  const api = useApi();
  const qc = useQueryClient();
  const isAdmin = useIsAdvocacyAdmin();
  const [openMatterId, setOpenMatterId] = useState<string | null>(() => initialOpenMatterId ?? null);
  useEffect(() => {
    if (initialOpenMatterId) onOpenMatterConsumed?.();
    // Intentionally NOT depending on onOpenMatterConsumed (an inline arrow
    // at the call site would otherwise re-fire this every parent render) —
    // only initialOpenMatterId's IDENTITY at mount time matters here.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);
  const [creating, setCreating] = useState(false);
  const [query, setQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState<string>('All');
  // §18/19: Matters is still the primary view (per the routing decision in
  // client-crm-routing.ts, Advocacy has not been promoted to its own
  // top-level tab this closeout) — Timeline is a secondary sub-view
  // reached via an in-page toggle, not a new URL param, matching the
  // existing pattern of keeping secondary-view state local to a tab
  // component rather than growing the shared route contract for every
  // internal toggle a tab wants.
  const [subView, setSubView] = useState<'matters' | 'timeline'>('matters');

  const matters = useQuery<AdvocacyMatterSummary[]>({
    queryKey: ['client-advocacy-matters', client.id],
    queryFn: async () =>
      (await api.get<AdvocacyMatterSummary[]>(`/api/clients/${client.id}/advocacy-matters`)).data,
  });

  const timeline = useQuery<AdvocacyTimelineEntry[]>({
    queryKey: ['client-advocacy-timeline', client.id],
    queryFn: async () =>
      (await api.get<AdvocacyTimelineEntry[]>(`/api/clients/${client.id}/advocacy-matters/timeline`)).data,
    enabled: subView === 'timeline',
  });

  const refreshList = () => void qc.invalidateQueries({ queryKey: ['client-advocacy-matters', client.id] });

  const createMatter = useMutation({
    mutationFn: async (input: { title: string; matterType: string }) =>
      (await api.post<{ id: string } | string>(`/api/clients/${client.id}/advocacy-matters`, input)).data,
    onSuccess: (created) => {
      setCreating(false);
      refreshList();
      // The create endpoint has returned two shapes across server versions:
      // the current `{ id }` object and an older bare UUID string. Reading
      // `.id` off the string yielded `undefined`, so the just-created Matter
      // never opened — accept both rather than depending on the deploy order.
      const id = typeof created === 'string' ? created : created?.id;
      if (id) setOpenMatterId(id);
    },
  });

  const loading = !matters.data && !matters.isError;
  const failed = matters.isError;
  const rows = matters.data ?? [];
  const genuinelyEmpty = matters.data !== undefined && !failed && rows.length === 0;

  // §24 search/filters: Matter title, ask (summary), issue code/PE/bill are
  // all fields AdvocacyMatterSummary already carries — no server-side
  // search endpoint needed for the list view, matching the exact
  // client-side query+filter pattern RelationshipsHistoryTab already uses
  // elsewhere in this same client-crm surface. Status options are derived
  // from what's actually present in this client's Matters, not the full
  // static STATUS_LABEL set — an empty "Withdrawn" chip when nothing here
  // is withdrawn would be noise, not a real filter.
  const statusOptions = useMemo(
    () => ['All', ...Array.from(new Set(rows.map((m) => m.status))).sort()],
    [rows],
  );
  const shown = useMemo(() => {
    const q = query.trim().toLowerCase();
    return rows.filter((matter) => {
      if (statusFilter !== 'All' && matter.status !== statusFilter) return false;
      if (!q) return true;
      const haystack = [matter.title, matter.summary, matter.primaryPeCode, matter.primaryBillId]
        .filter(Boolean)
        .join(' ')
        .toLowerCase();
      return haystack.includes(q);
    });
  }, [rows, query, statusFilter]);
  const nothingMatchesFilters = !genuinelyEmpty && !failed && !loading && rows.length > 0 && shown.length === 0;

  // Client Record v3: "Advocacy history — asks and outcomes, recorded
  // against the capability they support; 21px KPI figures." This tab had
  // no aggregate stat display before — every figure here is derived
  // straight from `rows` (the same AdvocacyMatterSummary[] the Matters
  // list and CardFoot's own count already render from), unfiltered by the
  // search/status controls — matching CardFoot's existing
  // rows.length-not-shown.length convention below, not a second or
  // fabricated source:
  //  - matterCount: rows.length — one ask per Matter (this file's own
  //    grouping model, see the doc comment above).
  //  - recordCount: sum of each Matter's recordCount — total underlying
  //    advocacy records (LDA filings, client submissions, private
  //    meeting/email evidence) captured across all Matters.
  //  - withOutcome: count of Matters whose outcomeCount > 0 — the same
  //    field MatterRow already surfaces per-row ("N with observed
  //    outcome"), aggregated rather than reinterpreted.
  //  - linkCount: sum of each Matter's linkCount — Program Elements,
  //    bills, hearings and other government objects tied to these Matters.
  // No status-derived "active"/"successful" KPI is included: mapping the
  // full legacy+current STATUS_LABEL set into one clean bucket isn't
  // unambiguous from the data alone, so per the "never fabricate" rule
  // it's left out rather than approximated.
  const kpis = useMemo(
    () => ({
      matterCount: rows.length,
      recordCount: rows.reduce((sum, m) => sum + m.recordCount, 0),
      withOutcome: rows.filter((m) => m.outcomeCount > 0).length,
      linkCount: rows.reduce((sum, m) => sum + m.linkCount, 0),
    }),
    [rows],
  );
  const kpiCells: Array<{ key: string; label: string; value: number }> = [
    { key: 'matters', label: 'Matters', value: kpis.matterCount },
    { key: 'records', label: 'Records captured', value: kpis.recordCount },
    { key: 'outcomes', label: 'With observed outcome', value: kpis.withOutcome },
    { key: 'links', label: 'Government objects linked', value: kpis.linkCount },
  ];

  return (
    <div className="cap-pf-anim-rise capiro-advocacy">
      {/* The page-level record-surface head already says "Advocacy history"
          with the prototype's description — a second TabPageHead here
          ("Advocacy matters") duplicated it the way the timeline's in-card
          CardHead did. The create action stays, right-aligned like the
          reference's header actions. */}
      {isAdmin ? (
        <div className="capiro-advocacy-head-actions">
          <PfButton variant="secondary" size="sm" onClick={() => setCreating(true)}>
            New matter
          </PfButton>
        </div>
      ) : null}
      <Card>
        <div className="capiro-advocacy-kpis" role="group" aria-label="Advocacy summary">
          {kpiCells.map((kpi) => (
            <div className="capiro-advocacy-kpi" key={kpi.key}>
              <span className="capiro-advocacy-kpi__value">
                {loading ? <PfSkeleton width={36} height={21} /> : failed ? '—' : kpi.value}
              </span>
              <span className="capiro-advocacy-kpi__label">{kpi.label}</span>
            </div>
          ))}
        </div>
      </Card>
      <SegmentedTabs
        ariaLabel="Advocacy view"
        options={[
          { key: 'matters', label: 'Matters' },
          { key: 'timeline', label: 'Timeline' },
        ]}
        value={subView}
        onChange={setSubView}
      />
      {subView === 'matters' ? (
      <Card>
        <CardHead
          title="Matters"
          description="Each Matter groups the advocacy asks, meetings, emails, submissions, filings, bills, Program Elements, and observed outcomes tied to one institutional ask."
          withDesc
        />
        {!loading && !failed && !genuinelyEmpty ? (
          <div className="capiro-advocacy-toolbar">
            <div className="capiro-advocacy-search">
              <UIcon name="SearchLg" size={20} color="var(--capiro-color-text-muted)" />
              <input
                value={query}
                onChange={(event) => setQuery(event.target.value)}
                aria-label="Search matters"
                placeholder="Search title, ask, PE, or bill"
              />
            </div>
            {statusOptions.map((s) => (
              <FilterChip
                key={s}
                label={s === 'All' ? 'All' : STATUS_LABEL[s] ?? s}
                active={statusFilter === s}
                onClick={() => setStatusFilter(s)}
              />
            ))}
          </div>
        ) : null}
        <div className="capiro-advocacy-list-body">
          {failed ? (
            <PfEmptyState
              title="Couldn't load advocacy matters"
              hint="Try again, or re-run Fill with Meri's Advocacy History specialist."
            />
          ) : loading ? (
            [0, 1, 2].map((i) => <MatterSkeletonRow key={i} last={i === 2} />)
          ) : genuinelyEmpty ? (
            <PfEmptyState
              title="No advocacy matters yet"
              hint="Matters are created automatically when Fill with Meri applies an advocacy record (LDA filings, client submissions, or private meeting/email advocacy) and clusters it by Program Element, bill, or subject. An admin can also create one manually."
            />
          ) : nothingMatchesFilters ? (
            <PfEmptyState
              title="No matters match your search"
              hint="Try a different term, or clear the status filter."
            />
          ) : (
            shown.map((matter) => (
              <MatterRow
                key={matter.id}
                matter={matter}
                onOpen={() => setOpenMatterId(matter.id)}
              />
            ))
          )}
        </div>
        {rows.length > 0 ? (
          <CardFoot left={`${rows.length} matter${rows.length === 1 ? '' : 's'}`} right={<span />} />
        ) : null}
      </Card>
      ) : (
        <TimelineCard
          entries={timeline.data ?? []}
          loading={!timeline.data && !timeline.isError}
          failed={timeline.isError}
          onOpenMatter={(id) => setOpenMatterId(id)}
        />
      )}

      {openMatterId ? (
        <AdvocacyMatterDrawer
          clientId={client.id}
          matterId={openMatterId}
          isAdmin={isAdmin}
          matterOptions={rows}
          onClose={() => setOpenMatterId(null)}
          onChanged={refreshList}
        />
      ) : null}

      {creating ? (
        <CapiroModal open title="New advocacy matter" onClose={() => setCreating(false)}>
          <CreateMatterForm
            busy={createMatter.isPending}
            error={createMatter.isError ? describeError(createMatter.error) : null}
            onCancel={() => setCreating(false)}
            onSubmit={(input) => createMatter.mutate(input)}
          />
        </CapiroModal>
      ) : null}
    </div>
  );
}

function describeError(error: unknown): string {
  const withResponse = error as { response?: { data?: { message?: string } } };
  return withResponse?.response?.data?.message ?? 'Something went wrong. Try again.';
}

function CreateMatterForm({
  busy,
  error,
  onCancel,
  onSubmit,
}: {
  busy: boolean;
  error: string | null;
  onCancel: () => void;
  onSubmit: (input: { title: string; matterType: string }) => void;
}) {
  const [title, setTitle] = useState('');
  const [matterType, setMatterType] = useState('other');
  return (
    <form
      className="capiro-advocacy-form"
      onSubmit={(e) => {
        e.preventDefault();
        if (title.trim()) onSubmit({ title: title.trim(), matterType });
      }}
    >
      <label className="capiro-advocacy-field-label">
        Title
        <input
          value={title}
          onChange={(e) => setTitle(e.target.value)}
          placeholder="e.g. FY27 Ground Robotics Funding"
          className="capiro-advocacy-field"
          autoFocus
        />
      </label>
      <label className="capiro-advocacy-field-label">
        Type
        <select
          value={matterType}
          onChange={(e) => setMatterType(e.target.value)}
          className="capiro-advocacy-field"
        >
          {MATTER_TYPE_OPTIONS.map((t) => (
            <option key={t} value={t}>
              {MATTER_TYPE_LABEL[t]}
            </option>
          ))}
        </select>
      </label>
      {error ? <span className="capiro-advocacy-form-error">{error}</span> : null}
      <div className="capiro-advocacy-form-actions capiro-advocacy-form-actions--spaced">
        <PfButton variant="secondary" size="sm" onClick={onCancel}>
          Cancel
        </PfButton>
        {/* PfButton renders type="button" — a form's primary action must
            trigger onSubmit itself, since a click never reaches the form
            handler otherwise (only Enter inside the input did). */}
        <span onClick={(e) => { e.preventDefault(); if (title.trim() && !busy) onSubmit({ title: title.trim(), matterType }); }}>
          <PfButton variant="primary" size="sm" disabled={!title.trim() || busy} busy={busy}>
            Create matter
          </PfButton>
        </span>
      </div>
    </form>
  );
}

