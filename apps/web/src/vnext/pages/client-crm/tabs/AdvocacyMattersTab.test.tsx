import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter } from 'react-router-dom';
import { describe, expect, it, vi, beforeEach } from 'vitest';
import { ClientCrmAdvocacyMattersProto } from './AdvocacyMattersTab.js';
import type { Client } from '../../../../pages/clients/clientTypes.js';

const getMock = vi.hoisted(() => vi.fn());
const postMock = vi.hoisted(() => vi.fn());
const patchMock = vi.hoisted(() => vi.fn());
vi.mock('../../../../lib/use-api.js', () => ({
  useApi: () => ({ get: getMock, post: postMock, patch: patchMock }),
}));

const meRoleMock = vi.hoisted(() => vi.fn(() => 'standard_user'));
vi.mock('../../../../lib/me.js', () => ({
  useMe: () => ({ data: { role: meRoleMock() } }),
}));

const client: Client = {
  id: 'client-1',
  name: 'Overland AI',
  website: 'overland.ai',
  description: null,
  productDescription: null,
  primaryContactName: null,
  primaryContactEmail: null,
  primaryContactPhone: null,
  logoS3Key: null,
  logoContentType: null,
  logoUploadedAt: null,
  intakeData: null,
  status: 'active',
  createdAt: '2026-01-15T00:00:00.000Z',
  updatedAt: '2026-01-15T00:00:00.000Z',
};

function renderMatters() {
  const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  return render(
    <QueryClientProvider client={queryClient}>
      <MemoryRouter>
        <ClientCrmAdvocacyMattersProto client={client} />
      </MemoryRouter>
    </QueryClientProvider>,
  );
}

const matterFixture = (overrides: Partial<Record<string, unknown>> = {}) => ({
  id: 'matter-1',
  title: '0605053A Program Element',
  matterType: 'program_element',
  status: 'active',
  summary: null,
  primaryPeCode: '0605053A',
  primaryBillId: null,
  externalKey: 'pe:0605053A',
  autoGenerated: true,
  openedAt: '2026-06-01T00:00:00.000Z',
  lastActivityAt: '2026-08-01T00:00:00.000Z',
  recordCount: 3,
  outcomeCount: 1,
  linkCount: 2,
  createdAt: '2026-06-01T00:00:00.000Z',
  updatedAt: '2026-08-01T00:00:00.000Z',
  ...overrides,
});

const recordFixture = (overrides: Partial<Record<string, unknown>> = {}) => ({
  id: 'rec-1',
  recordType: 'client_submission',
  title: 'FY27 ground robotics funding ask',
  summary: 'Requested funding increase for ground robotics.',
  activityDate: '2026-05-01T00:00:00.000Z',
  status: 'submitted',
  outcome: null,
  sourceType: 'client_submission',
  sourceId: 'sub-1',
  sourceUrl: null,
  evidenceClass: 'CLIENT_VERIFIED',
  confidence: 1,
  metadata: {},
  createdAt: '2026-05-01T00:00:00.000Z',
  matterLocked: false,
  ...overrides,
});

beforeEach(() => {
  getMock.mockReset();
  postMock.mockReset();
  patchMock.mockReset();
  meRoleMock.mockReset();
  meRoleMock.mockReturnValue('standard_user');
});

describe('ClientCrmAdvocacyMattersProto', () => {
  it('shows a real empty state when the client has no advocacy matters', async () => {
    getMock.mockResolvedValue({ data: [] });
    renderMatters();

    await waitFor(() => expect(screen.getByText('No advocacy matters yet')).toBeInTheDocument());
  });

  it('renders a matter grouped by record/outcome counts, not a flat per-record list', async () => {
    getMock.mockResolvedValue({ data: [matterFixture()] });
    renderMatters();

    await waitFor(() => expect(screen.getByText('0605053A Program Element')).toBeInTheDocument());
    expect(screen.getByText(/3 records/)).toBeInTheDocument();
    expect(screen.getByText(/1 with observed outcome/)).toBeInTheDocument();
  });

  it('opens a matter drawer with its records and links on click', async () => {
    getMock.mockImplementation(async (url: string) => {
      if (url.endsWith('/advocacy-matters')) {
        return { data: [matterFixture({ outcomeCount: 0, recordCount: 1, linkCount: 1 })] };
      }
      return {
        data: {
          ...matterFixture({
            summary: 'Automatically grouped from LDA filings and one client submission.',
            outcomeCount: 0,
            recordCount: 1,
            linkCount: 1,
          }),
          records: [recordFixture()],
          links: [{ id: 'link-1', linkType: 'bill', linkKey: '119-hr-1234', label: 'NDAA language', relationshipType: null, confidence: null, provenance: null, metadata: {} }],
        },
      };
    });
    renderMatters();

    await waitFor(() => expect(screen.getByText('0605053A Program Element')).toBeInTheDocument());
    fireEvent.click(screen.getByText('0605053A Program Element'));

    await waitFor(() =>
      expect(screen.getByText('FY27 ground robotics funding ask')).toBeInTheDocument(),
    );
    expect(screen.getByText('NDAA language')).toBeInTheDocument();
  });

  it('does not show admin correction actions to a standard_user', async () => {
    meRoleMock.mockReturnValue('standard_user');
    getMock.mockImplementation(async (url: string) => {
      if (url.endsWith('/advocacy-matters')) return { data: [matterFixture()] };
      return { data: { ...matterFixture(), records: [recordFixture()], links: [] } };
    });
    renderMatters();

    await waitFor(() => expect(screen.getByText('0605053A Program Element')).toBeInTheDocument());
    expect(screen.queryByText('New matter')).not.toBeInTheDocument();
    fireEvent.click(screen.getByText('0605053A Program Element'));
    await waitFor(() => expect(screen.getByText('FY27 ground robotics funding ask')).toBeInTheDocument());
    expect(screen.queryByText('Reassign')).not.toBeInTheDocument();
    expect(screen.queryByText('Detach')).not.toBeInTheDocument();
    expect(screen.queryByText('Not advocacy')).not.toBeInTheDocument();
    expect(screen.queryByText('Edit')).not.toBeInTheDocument();
  });

  it('shows admin correction actions to a user_admin and detaches a record', async () => {
    meRoleMock.mockReturnValue('user_admin');
    getMock.mockImplementation(async (url: string) => {
      if (url.endsWith('/advocacy-matters')) return { data: [matterFixture()] };
      return { data: { ...matterFixture(), records: [recordFixture()], links: [] } };
    });
    postMock.mockResolvedValue({ data: {} });
    renderMatters();

    await waitFor(() => expect(screen.getByText('0605053A Program Element')).toBeInTheDocument());
    expect(screen.getByText('New matter')).toBeInTheDocument();
    fireEvent.click(screen.getByText('0605053A Program Element'));
    await waitFor(() => expect(screen.getByText('FY27 ground robotics funding ask')).toBeInTheDocument());

    fireEvent.click(screen.getByText('Detach'));
    await waitFor(() => expect(screen.getByText('Detach record')).toBeInTheDocument());
    const dialogs = screen.getAllByRole('dialog');
    const modal = dialogs[dialogs.length - 1]!;
    fireEvent.click(within(modal).getByRole('button', { name: 'Detach' }));

    await waitFor(() =>
      expect(postMock).toHaveBeenCalledWith(
        '/api/clients/client-1/advocacy-matters/records/rec-1/detach',
      ),
    );
  });

  it('flags an auto-clustered matter and a manually-corrected record distinctly', async () => {
    meRoleMock.mockReturnValue('user_admin');
    getMock.mockImplementation(async (url: string) => {
      if (url.endsWith('/advocacy-matters')) return { data: [matterFixture({ autoGenerated: true })] };
      return {
        data: {
          ...matterFixture({ autoGenerated: true }),
          records: [recordFixture({ matterLocked: true })],
          links: [],
        },
      };
    });
    renderMatters();

    await waitFor(() => expect(screen.getByText('0605053A Program Element')).toBeInTheDocument());
    fireEvent.click(screen.getByText('0605053A Program Element'));
    await waitFor(() => expect(screen.getByText('Auto-clustered')).toBeInTheDocument());
    expect(screen.getByText('Corrected')).toBeInTheDocument();
  });

  it('requires explicit confirmation to set a Matter successful with no outcome evidence', async () => {
    meRoleMock.mockReturnValue('user_admin');
    getMock.mockImplementation(async (url: string) => {
      if (url.endsWith('/advocacy-matters')) return { data: [matterFixture({ outcomeCount: 0 })] };
      return { data: { ...matterFixture({ outcomeCount: 0 }), records: [], links: [] } };
    });
    renderMatters();

    await waitFor(() => expect(screen.getByText('0605053A Program Element')).toBeInTheDocument());
    fireEvent.click(screen.getByText('0605053A Program Element'));
    await waitFor(() => expect(screen.getByText('Edit')).toBeInTheDocument());
    fireEvent.click(screen.getByText('Edit'));

    await waitFor(() => expect(screen.getByText('Edit advocacy matter')).toBeInTheDocument());
    fireEvent.change(screen.getByDisplayValue('Active'), { target: { value: 'successful' } });

    const saveButton = screen.getByRole('button', { name: 'Save' });
    expect(saveButton).toBeDisabled();

    fireEvent.click(screen.getByRole('checkbox'));
    expect(saveButton).not.toBeDisabled();
  });
});
