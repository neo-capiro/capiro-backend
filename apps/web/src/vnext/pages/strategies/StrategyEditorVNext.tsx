/*
 * The timeline is a MONTH-COLUMN GRID, not a free track.
 *
 * The reference design (`.dc.html` "Working timeline") lays every band out as
 * `grid-template-columns: repeat(n, minmax(colW, 1fr))` and places each bar
 * with `grid-column: <start> / span <n>`. This file used to position bars as
 * `left/width` percentages inside a relatively-positioned track instead, which
 * cost three things the grid gives for free:
 *
 *  - a bar's box IS its grid area, so a label can never spill past the bar it
 *    belongs to (it ellipsizes inside it);
 *  - bars land exactly on their month tick at every viewport, with no shared
 *    percentage frame to drift;
 *  - the label gutter is a sibling column outside the scroller rather than a
 *    sticky overlay inside it, so nothing is ever painted over it.
 *
 * Lane packing runs on COLUMN ranges (assignColumnLanes) rather than
 * timestamps: two bars can be disjoint in time and still share a month cell.
 */

/** Row heights, verbatim from the reference file. */
const FY_ROW_H = 34;
const MONTH_ROW_H = 28;
const HEADER_ROW_H = FY_ROW_H + MONTH_ROW_H; // 62px gutter row for the fiscal window
const REF_LANE_H = 26;
const REF_LANE_GAP = 6;
const REF_BAND_PAD = 16; // padding: 8px 0
const STEP_CARD_H = 72;
const STEP_LANE_GAP = 8;
const STEP_BAND_PAD = 24; // padding: 10px 0 14px

const refBandHeight = (lanes: number) =>
  REF_BAND_PAD + lanes * REF_LANE_H + Math.max(0, lanes - 1) * REF_LANE_GAP;
const stepBandHeight = (lanes: number) =>
  STEP_BAND_PAD + lanes * STEP_CARD_H + Math.max(0, lanes - 1) * STEP_LANE_GAP;

/**
 * Minimum columns a bar is widened to so it can render its own label.
 * A point-in-time step (a gate with no end date) is one month wide, which at
 * the 36-month density is ~46px — narrower than the word "ACTION". The real
 * dates stay authoritative in the step inspector and the bar's tooltip; this
 * only affects what is drawn. Wider columns need less padding.
 */
const stepMinSpan = (colW: number) => (colW >= 92 ? 2 : colW >= 62 ? 3 : 3);
const refMinSpan = (colW: number) => (colW >= 92 ? 1 : 2);

/** `YYYY-MM-DD` from whatever the API hands back (date-only or full UTC ISO). */
function dateOnly(iso: string | null): string | null {
  if (!iso) return null;
  if (/^\d{4}-\d{2}-\d{2}$/.test(iso)) return iso;
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? null : toDateOnly(d);
}

interface TimelineProps {
  axis: TimelineAxis;
  layers: { congress: boolean; ppbe: boolean; watch: boolean };
  nodes: StrategyNode[];
  firmPhases: FirmPhase[];
  congress: ReferenceRow[];
  congressIsFork: boolean;
  ppbe: ReferenceRow[];
  members: ReturnType<typeof useTenantMembers>['data'];
  selectedStepId: string | null;
  watchProposals: WatchProposalCard[];
  onStepClick: (id: string) => void;
  onWatchClick: () => void;
  onPhaseClick: () => void;
}

function Timeline({
  axis,
  layers,
  nodes,
  firmPhases,
  congress,
  congressIsFork,
  ppbe,
  members,
  selectedStepId,
  watchProposals,
  onStepClick,
  onWatchClick,
  onPhaseClick,
}: TimelineProps) {
  // One stable instant per mount: every band memo keys off it, and a fresh
  // `new Date()` each render would invalidate all of them on every keystroke.
  const today = useMemo(() => new Date(), []);
  const monthCount = axis.cells.length;
  const colW = monthColumnWidth(monthCount);
  const todayFraction = axisPosition(axis, today);
  const showToday = todayFraction >= 0 && todayFraction <= 1;
  const todayYear = today.getUTCFullYear();
  const todayMonth = today.getUTCMonth() + 1;
  const todayColumn = Math.min(Math.max(monthIndexOf(axis, today), 0), monthCount - 1);

  const [editingCalendar, setEditingCalendar] = useState(false);

  const fiscalYears = useMemo(() => {
    const years: Array<{ fy: number; start: number; span: number }> = [];
    axis.cells.forEach((cell, i) => {
      const last = years[years.length - 1];
      if (last && last.fy === cell.fy) last.span += 1;
      else years.push({ fy: cell.fy, start: i, span: 1 });
    });
    return years;
  }, [axis]);

  const fyShort = (fy: number) => `FY${String(fy).slice(2)}`;
  const windowLabel =
    axis.startFy === axis.endFy
      ? `${fyShort(axis.startFy)} window`
      : axis.endFy - axis.startFy === 1
        ? `${fyShort(axis.startFy)}–${fyShort(axis.endFy)} window`
        : '3-FY window';

  /* Reference bands, in reference-file order. Each returns its own laned bars
     so the gutter can be sized to exactly the same height as the band. */
  const ppbeBand = useReferenceBand(axis, ppbe, colW, today);
  const phaseBand = useFirmPhaseBand(axis, firmPhases, colW);
  const watchBand = useWatchBand(axis, watchProposals, colW);
  const stepBand = useStepBand(axis, nodes, colW);

  const legislative = useLegislativeBand({
    axis,
    rows: congress,
    colW,
    today,
    todayColumn,
    isFork: congressIsFork,
    editing: editingCalendar,
    onEditingChange: setEditingCalendar,
  });

  const gutterRows: Array<{ key: string; label: string; height: number; extra?: React.ReactNode }> = [
    { key: 'window', label: windowLabel, height: HEADER_ROW_H },
  ];
  if (layers.congress) {
    gutterRows.push({
      key: 'congress',
      label: 'Legislative',
      height: legislative.height,
      extra: (
        <button
          type="button"
          className="st-tl__gutter-edit"
          aria-pressed={editingCalendar}
          onClick={() => setEditingCalendar((v) => !v)}
        >
          {editingCalendar ? 'Done' : 'Edit'}
        </button>
      ),
    });
  }
  if (layers.ppbe) gutterRows.push({ key: 'ppbe', label: 'PPBE', height: ppbeBand.height });
  gutterRows.push({ key: 'phases', label: 'Firm phases', height: phaseBand.height });
  if (layers.watch) gutterRows.push({ key: 'watch', label: 'Watch', height: watchBand.height });
  gutterRows.push({ key: 'steps', label: 'Strategy steps', height: stepBand.height });

  return (
    <div className="st-tl" role="group" aria-label="Strategy timeline">
      <div className="st-tl__frame">
        {/* Label gutter — a sibling of the scroller, not a sticky overlay inside
            it, exactly as the reference draws it. It never scrolls and nothing
            is ever painted across it. NOT aria-hidden: it carries the
            calendar's Edit control, and hiding a focusable button from the
            accessibility tree makes it unreachable by anything but a mouse. */}
        <div className="st-tl__gutter">
          {gutterRows.map((r, i) => (
            <div
              key={r.key}
              className={`st-tl__gutter-row${i === 0 ? ' st-tl__gutter-row--header' : ''}${
                i === gutterRows.length - 1 ? ' st-tl__gutter-row--last' : ''
              }`}
              style={{ height: r.height }}
            >
              <span className="st-tl__gutter-label">{r.label}</span>
              {r.extra}
            </div>
          ))}
        </div>

        <div className="st-tl__scroll">
          <div
            className="st-tl__canvas"
            style={
              {
                '--st-tl-cols': monthCount,
                '--st-tl-col-w': `${colW}px`,
                '--st-tl-col-pct': `${(100 / monthCount).toFixed(4)}%`,
              } as React.CSSProperties
            }
          >
            {/* Fiscal-year header. */}
            <div className="st-tl__fyrow">
              {fiscalYears.map((y) => (
                <div
                  key={y.fy}
                  className="st-tl__fycell"
                  style={{ gridColumn: `${y.start + 1} / span ${y.span}` }}
                >
                  {fyShort(y.fy)}
                </div>
              ))}
            </div>

            {/* Month ruler. */}
            <div className="st-tl__monthrow">
              {axis.cells.map((c) => {
                const isCurrentMonth = c.year === todayYear && c.month === todayMonth;
                return (
                  <div
                    key={c.index}
                    className={`st-tl__month${c.fiscalYearStart ? ' st-tl__month--fy' : ''}${
                      isCurrentMonth ? ' st-tl__month--current' : ''
                    }`}
                  >
                    {c.label}
                  </div>
                );
              })}
            </div>

            {layers.congress ? legislative.band : null}
            {layers.ppbe ? (
              <TimelineBand height={ppbeBand.height} label="PPBE reference calendar">
                {ppbeBand.bars.map(({ item, lane }) => (
                  <TimelineBar
                    key={item.id}
                    span={item.span}
                    lane={lane}
                    label={item.label}
                    tone={item.tone}
                    title={item.title}
                    readOnly
                  />
                ))}
                {ppbeBand.bars.length === 0 ? <BandEmpty>No PPBE marks in this window.</BandEmpty> : null}
              </TimelineBand>
            ) : null}

            <TimelineBand height={phaseBand.height} label="Firm phases">
              {phaseBand.bars.map(({ item, lane }) => (
                <TimelineBar
                  key={item.id}
                  span={item.span}
                  lane={lane}
                  label={item.label}
                  tone="phase"
                  title={`Firm phase ${item.label}`}
                  onClick={onPhaseClick}
                />
              ))}
              {phaseBand.bars.length === 0 ? (
                <BandEmpty>Set firm phases to light up the reference layer.</BandEmpty>
              ) : null}
            </TimelineBand>

            {layers.watch ? (
              <TimelineBand height={watchBand.height} label="Watch proposals">
                {watchBand.bars.map(({ item, lane }) => (
                  <TimelineBar
                    key={item.id}
                    span={item.span}
                    lane={lane}
                    label={item.label}
                    tone="watch"
                    title={item.title}
                    onClick={onWatchClick}
                  />
                ))}
                {watchBand.bars.length === 0 ? (
                  <TimelineBar
                    span={{ start: 0, span: Math.min(8, monthCount), clippedStart: false, clippedEnd: false, trueSpan: 1 }}
                    lane={0}
                    label="No pending proposals — review queue"
                    tone="watch"
                    title="Open the agent review queue"
                    onClick={onWatchClick}
                  />
                ) : null}
              </TimelineBand>
            ) : null}

            {/* Strategy steps — the plan itself. */}
            <div className="st-tl__band st-tl__band--steps" style={{ height: stepBand.height }}>
              {stepBand.bars.map(({ item, lane }) => {
                const node = item.node;
                const selected = node.id === selectedStepId;
                const owner = memberName(members, node.ownerUserId);
                /*
                 * A point-in-time step (a gate or milestone with no end date)
                 * is drawn wider than one month so its own label fits — see
                 * `stepMinSpan`. Padding the box without saying so would claim
                 * a duration the step does not have, so the card carries a
                 * solid edge on its true start date and names that date in its
                 * tooltip and accessible label. `trueSpan` is the pre-padding
                 * width, which is why the geometry keeps it.
                 */
                const instant = !node.endsOn && item.span.trueSpan === 1 && item.span.span > 1;
                return (
                  <button
                    key={node.id}
                    type="button"
                    className={`st-step st-step--${node.kind}${selected ? ' st-step--selected' : ''}${
                      instant ? ' st-step--instant' : ''
                    }`}
                    style={{
                      gridColumn: `${item.span.start + 1} / span ${item.span.span}`,
                      gridRow: `${lane + 1} / span 1`,
                    }}
                    onClick={() => onStepClick(node.id)}
                    title={instant ? `${node.title} — ${formatDate(node.startsOn)}` : node.title}
                    aria-label={`${KIND_LABEL[node.kind] ?? node.kind}: ${node.title}${
                      instant ? `, on ${formatDate(node.startsOn)}` : ''
                    }`}
                    aria-pressed={selected}
                  >
                    <span className={`st-step__kind st-step__kind--${node.kind}`}>
                      <span className="st-step__dot" aria-hidden="true" />
                      <span className="st-step__kind-text">{KIND_LABEL[node.kind] ?? node.kind}</span>
                    </span>
                    <span className="st-step__title">{node.title}</span>
                    <span className="st-step__meta">
                      {node.ownerUserId ? `Owner · ${owner}` : 'Unassigned'}
                    </span>
                  </button>
                );
              })}
            </div>

            {showToday ? (
              <>
                <span
                  className="st-tl__today-line"
                  style={{ left: `${todayFraction * 100}%` }}
                  aria-hidden="true"
                />
                <span className="st-tl__today-pill" style={{ left: `${todayFraction * 100}%` }}>
                  <span className="st-tl__today-dot" aria-hidden="true" />
                  Today
                </span>
              </>
            ) : null}
          </div>
        </div>
      </div>

      {layers.congress ? legislative.footer : null}
    </div>
  );
}

