const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const cp = require('node:child_process');
const root = path.resolve(__dirname, '../../..');
const ts = require(require.resolve('typescript', { paths: [path.join(root, 'apps/api')] }));
const z = require('/workspace/capiro-frontend/node_modules/zod');
const bindings = JSON.parse(fs.readFileSync(path.join(__dirname, 'READ-BINDINGS.json'), 'utf8'));
const row = bindings.rows.find(row => row.repository === 'capiro-frontend' && row.path.endsWith('/operations/engagement.ts'));
const source = cp.execFileSync('git', ['show', `${row.ref}:${row.path}`], { cwd: '/workspace/capiro-frontend', encoding: 'utf8' });
const digest = value => crypto.createHash('sha256').update(value).digest('hex');
assert.equal(digest(source), row.sha256);
const ast = ts.createSourceFile('engagement.ts', source, ts.ScriptTarget.Latest, true);
const names = ['id', 'client', 'outreachRecord'];
const statements = ast.statements.filter(statement => ts.isVariableStatement(statement) && statement.declarationList.declarations.some(declaration => names.includes(declaration.name.getText(ast))));
assert.equal(statements.length, 3);
const selected = `${statements.map(statement => statement.getText(ast)).join('\n')}\nexports.schema=outreachRecord;`;
assert.equal(selected, fs.readFileSync(path.join(__dirname, 'frontend-parser-actual-declarations.ts.txt'), 'utf8'));
const original = JSON.parse(fs.readFileSync(path.join(__dirname, 'frontend-parser-strip-receipt.json'), 'utf8'));
assert.equal(digest(selected), original.declarationSha256);
const context = { exports: {}, z };
vm.runInNewContext(ts.transpileModule(selected, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context, { timeout: 1000 });
const checks = original.checks.map(({ inputMetadata }) => {
  const value = { id: '11111111-1111-4111-8111-111111111111', title: 'Synthetic', type: 'outbound_campaign', status: 'draft', subject: null, body: null, metadata: inputMetadata };
  const output = context.exports.schema.parse(value);
  assert.equal(Object.hasOwn(output, 'metadata'), false);
  assert.equal(output.id, value.id);
  assert.equal(output.type, value.type);
  return { inputMetadata, outputMetadataPresent: false, knownIdTypeRetained: true };
});
assert.deepEqual(checks, original.checks);
assert.equal(require('/workspace/capiro-frontend/node_modules/zod/package.json').version, original.zodVersion);
process.stdout.write(JSON.stringify({ checks: checks.length, sourceHashVerified: true, exactDeclarationsVerified: true, originalReceiptReproduced: true, transportImported: false, frontendModified: false }, null, 2) + '\n');
